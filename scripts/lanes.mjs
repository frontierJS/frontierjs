// ============================================================
// Lanes — one git worktree per concurrent loop session
//
// A loop runs one row per session, and a session spends four
// fifths of its wall time waiting on suites and drives, so rows
// run side by side. Side by side in ONE tree they would not be
// isolated: a half-edited litestone breaks the junction suite a
// neighbor is running, and two drives want one port. A lane is a
// linked worktree, so ports.js gives it its own port block, and
// what it changes reaches the main tree only when its row ends.
//
// What a lane holds is the main tree as it is when the row starts —
// HEAD, every uncommitted edit, every untracked file — so its
// session sees what a serial one would. Two kinds of file are not
// copied:
//
// - The register is LINKED. `ISSUES.md` and its neighbors in a lane
//   are symlinks to the main tree's, so `fli close` and `fli file`
//   write there live, through `withRegisterGuard`, and an id minted
//   in one lane is taken in every other. A merged copy would hand two
//   lanes the same next id. Edit refuses a link and names its target,
//   which is why the session gets `--add-dir` on the main tree.
//   A trial lane (`syncLane(lane, { linked: false })`) COPIES it instead:
//   two models fixing one row must not both close it in the main tree,
//   so each closes its own copy and the register edit rides in the patch.
// - What the row changes is HARVESTED: each file it touched is merged
//   three ways into the main tree — what the lane started from, what
//   the main tree holds now, what the lane ends with — and nothing is
//   written unless every file merges, so a conflict leaves the main
//   tree as it was and the lane as the session left it.
//
// Lanes persist under ~/.fli/lanes and are reused, because an install
// is the slow part of making one.
// ============================================================

import { spawnSync }                                                         from 'node:child_process'
import { copyFileSync, existsSync, lstatSync, mkdirSync, readFileSync,
         rmSync, symlinkSync, unlinkSync, writeFileSync, chmodSync }         from 'node:fs'
import { basename, dirname, join }                                          from 'node:path'

import { ROOT, LOG_DIR }  from './headless.mjs'
import { fenceBunGlobal } from '../packages/cli/core/bun-fence.js'

export const LANES_DIR = join(LOG_DIR, 'lanes')

/** The register, linked rather than copied — one origin, written live. */
export const LINKED = ['ISSUES.md', 'ISSUES_ARCHIVE.md', 'DECISIONS.md', 'IDEAS/owed-rulings.md']

// Regenerated by `fli snapshots --fix`, so a conflict in one is dropped with a
// note rather than failing the harvest.
const GENERATED = /(^|\/)[^/]*\.snapshot\.[a-z]+$|^codegraph\.html$/

const EXCLUDE = LINKED.map(f => `:(exclude)${f}`)

// Sierra's import-fresh sidecar: a copy a test writes beside a module and
// removes once the import resolves. A snapshot taken while one exists would
// carry it into the patch, and the harvest would write it into the main tree.
const SCRATCH_PATHSPEC = ':(exclude,glob)**/.sierra-fresh-*'
const SCRATCH = /(^|\/)\.sierra-fresh-[^/]*$/

/** ports.js has five port blocks for linked worktrees. */
export const MAX_LANES = 5

/** The first `count` lanes no other running loop holds, each opened. */
export function openLanes(count) {
  const got = []
  for (let n = 1; n <= MAX_LANES && got.length < count; n++) if (claim(n)) got.push(openLane(n))
  if (got.length < count) throw new Error(`${count} lanes asked, ${got.length} free: another loop holds the rest (${LANES_DIR}/*.lock)`)
  return got
}

/** The lane numbered `n`, made and installed if it does not exist yet. */
export function openLane(n) {
  if (!claim(n)) throw new Error(`lane ${n} is held by pid ${holder(n)}, a loop still running`)
  const dir = join(LANES_DIR, `${basename(ROOT)}-${n}`)
  const bin = join(LANES_DIR, `bin-${n}`)
  if (!isWorktree(dir)) {
    rmSync(dir, { recursive: true, force: true })
    git(ROOT, 'worktree', 'prune')
    git(ROOT, 'worktree', 'add', '--detach', dir, 'HEAD')
    const install = spawnSync('bun', ['install', '--frozen-lockfile'], { cwd: dir, encoding: 'utf8' })
    if (install.status !== 0) throw new Error(`lane ${n}: bun install failed\n${install.stderr}`)
    // Gitignored, so the worktree has none: the app reads its secrets and ports here.
    for (const f of run('rg', ['--files', '--hidden', '--no-ignore', '-g', '.env', '-g', '.env.*', '-g', '!**/node_modules/**', '-g', '!.git'], ROOT).split('\n').filter(Boolean)) {
      mkdirSync(dirname(join(dir, f)), { recursive: true })
      copyFileSync(join(ROOT, f), join(dir, f))
    }
  }
  // The global `fli` is the main tree's build, so a fix to the cli would be
  // proved with the code it replaced; the lane's own goes first on PATH.
  mkdirSync(bin, { recursive: true })
  writeFileSync(join(bin, 'fli'), `#!/bin/sh\nexec bun ${JSON.stringify(join(dir, 'packages', 'cli', 'bin', 'fli.js'))} "$@"\n`)
  chmodSync(join(bin, 'fli'), 0o755)
  return { n, dir, bin, env: laneEnv(bin, join(LANES_DIR, `bun-${n}`)) }
}

/**
 * What a lane's session runs under. `bun link` keeps one global link per name
 * and the last tree to link wins, so a session that links from the lane
 * re-points the machine's `fli` and every `@frontierjs/*` link into it; the
 * fence gives the lane a global dir of its own (FJS-1364, FJS-3258).
 */
export function laneEnv(bin, fence, base = process.env) {
  const { env } = fenceBunGlobal(base, fence)
  return { BUN_INSTALL: env.BUN_INSTALL, BUN_INSTALL_CACHE_DIR: env.BUN_INSTALL_CACHE_DIR, PATH: `${bin}:${base.PATH}` }
}

/**
 * Make the lane the main tree as it is now, and answer the tree id the harvest
 * is measured from.
 */
export function syncLane(lane, { linked = true } = {}) {
  const { dir } = lane
  lane.linked = linked
  // Unlinked first: a reset must never write through a link into the main tree.
  for (const f of LINKED) if (isLink(join(dir, f))) unlinkSync(join(dir, f))
  // A linked run leaves the bit set, and a copy it hides never shows in a trial's diff.
  git(dir, 'update-index', '--no-skip-worktree', ...LINKED)
  git(dir, 'reset', '-q', '--hard', git(ROOT, 'rev-parse', 'HEAD'))
  git(dir, 'clean', '-fdq')

  const patch = run('git', ['-C', ROOT, 'diff', 'HEAD', '--binary', '--no-color', '--no-ext-diff', '--', '.', ...EXCLUDE], ROOT, { raw: true })
  if (patch.length) {
    const out = spawnSync('git', ['-C', dir, 'apply', '--whitespace=nowarn', '-'], { input: patch })
    if (out.status !== 0) throw new Error(`the main tree's uncommitted diff does not apply in ${dir}: ${out.stderr}`)
  }
  for (const f of run('git', ['-C', ROOT, 'ls-files', '--others', '--exclude-standard', '-z'], ROOT).split('\0').filter(f => f && !SCRATCH.test(f))) {
    copyIfPresent(join(ROOT, f), join(dir, f))
  }

  for (const f of LINKED) {
    if (existsSync(join(dir, f))) unlinkSync(join(dir, f))
    if (linked) symlinkSync(join(ROOT, f), join(dir, f))
    else copyFileSync(join(ROOT, f), join(dir, f))
  }
  // A link where the index holds a file reads as a change; the lane's git
  // status then looks as the main tree's does.
  if (linked) git(dir, 'update-index', '--skip-worktree', ...LINKED)
  return snapshot(lane)
}

/**
 * Copy `src` to `dest`, true when it was copied. A file the main tree lists as
 * untracked can be another session's test scratch, deleted between the listing
 * and the copy; a vanished source is no file to carry, and throwing on it
 * means the row never starts.
 */
export function copyIfPresent(src, dest) {
  try {
    mkdirSync(dirname(dest), { recursive: true })
    copyFileSync(src, dest)
    return true
  } catch (err) {
    if (err?.code === 'ENOENT' && !existsSync(src)) return false
    throw err
  }
}

/** Lay a saved patch onto the lane; false when it no longer applies. */
export function applyPatch({ dir }, file) {
  if (!existsSync(file)) return false
  return spawnSync('git', ['-C', dir, 'apply', '--whitespace=nowarn', file]).status === 0
}

/** What the lane changed since `base`, as a patch `applyPatch` takes. */
export function lanePatch(lane, base) {
  return run('git', ['-C', lane.dir, 'diff-tree', '-p', '--binary', '--no-color', base, snapshot(lane)], lane.dir, { raw: true })
}

/**
 * Merge what the lane changed since `base` into the main tree. Answers
 * `{ written, dropped, conflicts }`; with any conflict nothing was written.
 */
export function harvest(lane, base) {
  const { dir } = lane
  const after   = snapshot(lane)
  const changes = run('git', ['-C', dir, 'diff-tree', '-r', '-z', '--no-renames', '--name-status', base, after], dir).split('\0').filter(Boolean)
  const plan = [], dropped = [], conflicts = []

  for (let i = 0; i < changes.length; i += 2) {
    const [status, path] = [changes[i], changes[i + 1]]
    const was  = blob(dir, base, path)
    const now  = blob(dir, after, path)
    const main = existsSync(join(ROOT, path)) ? readFileSync(join(ROOT, path)) : null
    const merged = merge(was, main, now, path)
    if (merged === undefined) (GENERATED.test(path) ? dropped : conflicts).push(path)
    else if (!same(merged, main)) plan.push({ path, content: merged, status })
  }
  if (conflicts.length) return { written: [], dropped, conflicts }

  for (const { path, content } of plan) {
    if (content === null) { rmSync(join(ROOT, path), { force: true }); continue }
    mkdirSync(dirname(join(ROOT, path)), { recursive: true })
    writeFileSync(join(ROOT, path), content)
  }
  return { written: plan.map(p => p.path), dropped, conflicts }
}

// The content the main tree should hold, `null` for absent, or undefined for a
// conflict. Only a text change both sides made is merged line by line.
function merge(was, main, now, path) {
  if (same(main, was) || same(main, now)) return now
  if (same(now, was)) return main
  if (was === null || main === null || now === null) return undefined
  const tmp = join(LANES_DIR, 'merge', String(process.pid))
  mkdirSync(tmp, { recursive: true })
  const [a, b, c] = ['main', 'base', 'lane'].map(n => join(tmp, `${n}-${basename(path)}`))
  writeFileSync(a, main); writeFileSync(b, was); writeFileSync(c, now)
  const out = spawnSync('git', ['merge-file', '-p', a, b, c], { maxBuffer: 256 << 20 })
  rmSync(tmp, { recursive: true, force: true })
  return out.status === 0 ? out.stdout : undefined
}

// A tree object of the lane's working files, built in a throwaway index so the
// lane's own index — and so its `git status` — stays as the main tree's is.
// A linked register is the main tree's file and never part of the lane's change.
function snapshot({ dir, linked = true }) {
  const index = join(LANES_DIR, `index-${process.pid}-${basename(dir)}`)
  copyFileSync(git(dir, 'rev-parse', '--path-format=absolute', '--git-path', 'index'), index)
  try {
    const env = { ...process.env, GIT_INDEX_FILE: index }
    for (const argv of [['add', '-A', '--', '.', SCRATCH_PATHSPEC, ...(linked ? EXCLUDE : [])], ['write-tree']]) {
      const out = spawnSync('git', ['-C', dir, ...argv], { env, encoding: 'utf8', maxBuffer: 64 << 20 })
      if (out.status !== 0) throw new Error(`git ${argv[0]} in ${dir}: ${out.stderr}`)
      if (argv[0] === 'write-tree') return out.stdout.trim()
    }
  } finally { rmSync(index, { force: true }) }
}

// ─── claims ─────────────────────────────────────────────────

// A second loop opening a lane the first is running in resets it under that
// session mid-prove, so the fix it then reports is one the harvest never
// carries (FJS-3238). A claim is the holder's pid, freed when it exits; a
// claim whose pid is gone was left by a killed loop and is taken over.
const claimed = new Set()
const lockOf  = n => join(LANES_DIR, `${basename(ROOT)}-${n}.lock`)

function claim(n) {
  if (claimed.has(n)) return true
  mkdirSync(LANES_DIR, { recursive: true })
  for (let tries = 0; tries < 2; tries++) {
    try { writeFileSync(lockOf(n), String(process.pid), { flag: 'wx' }) }
    catch (err) {
      if (err.code !== 'EEXIST') throw err
      if (alive(holder(n))) return false
      rmSync(lockOf(n), { force: true })
      continue
    }
    if (claimed.size === 0) process.on('exit', () => { for (const m of claimed) if (holder(m) === process.pid) rmSync(lockOf(m), { force: true }) })
    claimed.add(n)
    return true
  }
  return false
}

function holder(n) {
  try { return Number(readFileSync(lockOf(n), 'utf8')) } catch { return 0 }
}

function alive(pid) {
  if (!pid) return false
  try { process.kill(pid, 0); return true } catch (err) { return err.code === 'EPERM' }
}

function blob(dir, tree, path) {
  const out = spawnSync('git', ['-C', dir, 'cat-file', 'blob', `${tree}:${path}`], { maxBuffer: 256 << 20 })
  return out.status === 0 ? out.stdout : null
}

const same = (a, b) => a === null || b === null ? a === b : Buffer.compare(a, b) === 0

function isWorktree(dir) {
  const out = spawnSync('git', ['-C', dir, 'rev-parse', '--show-toplevel'], { encoding: 'utf8' })
  return out.status === 0 && out.stdout.trim() === dir
}

function isLink(path) {
  try { return lstatSync(path).isSymbolicLink() } catch { return false }
}

function git(cwd, ...argv) {
  return run('git', ['-C', cwd, ...argv], cwd).trim()
}

function run(cmd, argv, cwd, { raw = false } = {}) {
  const out = spawnSync(cmd, argv, { cwd, encoding: raw ? 'buffer' : 'utf8', maxBuffer: 256 << 20 })
  if (out.status !== 0 && cmd !== 'rg') throw new Error(`${cmd} ${argv.join(' ')}: ${out.stderr}`)
  return out.stdout ?? (raw ? Buffer.alloc(0) : '')
}
