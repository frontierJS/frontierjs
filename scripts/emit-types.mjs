#!/usr/bin/env node
// ─── emit-types.mjs — declarations for a plain-JS package's exports ──────────
//
//   bun run types            # write them, from the package directory
//   bun run types -- --check # fail when one is missing, drifted or stale
//
// A JS export with no `types` condition is TS7016 in an app installed from the
// package host. `link:` hid it, because tsc followed the symlink out of
// node_modules and read the JS as source (FJS-3720). The ruling is FJS-D1746:
// generate the `.d.ts` from the JS, commit it beside the source, and fail the
// package's test when it drifts.
//
// Which files are generated is read off `exports`: an entry whose `types` file
// is absent or opens with HEADER. A `types` file without the header is
// hand-written and is never touched. In write mode a bare `"./x.js"` entry
// becomes `{ types, default }` and an `{ import }` one gains `types`; under
// `--check` either is a failure, since a new kit added that way is the
// regression this guards.
//
// An untyped JS parameter emits as required, so a caller that omits it is
// TS2554 against the declaration: `/** @param {T} [x] */` on the JS is the fix.
//
// The emit runs over a temp copy with every generated file removed: left in
// place, an import of `./helper.js` resolves to the committed `helper.d.ts`, and
// a changed helper would regenerate as its old self.

import { spawnSync }                                  from 'node:child_process'
import { cpSync, existsSync, mkdtempSync, readdirSync, readFileSync,
         rmSync, symlinkSync, writeFileSync, mkdirSync } from 'node:fs'
import { tmpdir }                                     from 'node:os'
import { basename, dirname, join, relative }          from 'node:path'

import { findTsc }                                    from '../packages/cli/core/typecheck.js'

const HEADER = '// Generated by scripts/emit-types.mjs'
const SKIP   = new Set(['node_modules', '.git', 'dist'])

const args  = process.argv.slice(2)
const check = args.includes('--check')
const bad   = args.find(a => a !== '--check')
if (bad) fail(`unknown argument ${bad} — the only flag is --check`)

const pkgDir   = process.cwd()
const manifest = join(pkgDir, 'package.json')
if (!existsSync(manifest)) fail('run from a package directory — no package.json here')

const pkg      = JSON.parse(readFileSync(manifest, 'utf8'))
const problems = []

const roots = collectRoots(pkg)
if (roots.length === 0) {
  report()
  process.exit(0)
}

const emitted = emit(roots)
compare(emitted)
report()

// ─── reading exports ─────────────────────────────────────────────────────────

function collectRoots(pkg) {
  const roots = []
  let rewrote = false

  for (const [subpath, target] of Object.entries(pkg.exports ?? {})) {
    if (subpath.includes('*')) continue

    if (typeof target === 'string') {
      if (!target.endsWith('.js') || isClassicScript(join(pkgDir, target))) continue
      if (check) {
        problems.push(`exports["${subpath}"] is a bare ${target} with no types condition — run bun run types`)
        continue
      }
      pkg.exports[subpath] = { types: target.replace(/\.js$/, '.d.ts'), default: target }
      rewrote = true
      roots.push(target)
      continue
    }

    const { types, import: esm, default: fallback } = target ?? {}
    const entry = esm ?? fallback
    if (typeof entry !== 'string' || !entry.endsWith('.js')) continue
    if (types === undefined) {
      if (isClassicScript(join(pkgDir, entry))) continue
      if (check) {
        problems.push(`exports["${subpath}"] names ${entry} with no types condition — run bun run types`)
        continue
      }
      // `types` leads: conditions match in key order, and tsc stops at the first.
      pkg.exports[subpath] = { types: entry.replace(/\.js$/, '.d.ts'), ...target }
      rewrote = true
      roots.push(entry)
      continue
    }
    if (typeof types !== 'string') continue
    if (types !== entry.replace(/\.js$/, '.d.ts')) continue
    if (isHandWritten(join(pkgDir, types))) continue
    roots.push(entry)
  }

  if (rewrote) writeFileSync(manifest, JSON.stringify(pkg, null, 2) + '\n')
  return roots
}

// A classic script declares globals and exports nothing, so its emit is a file
// of globals that an import answers with TS2306 — css's vocabulary.js, which a
// page loads with a script tag.
function isClassicScript(file) {
  return existsSync(file) && !/^\s*(?:import|export)\b/m.test(readFileSync(file, 'utf8'))
}

function isGenerated(file) {
  return existsSync(file) && readFileSync(file, 'utf8').startsWith(HEADER)
}

function isHandWritten(file) {
  return existsSync(file) && !isGenerated(file)
}

// ─── emitting ────────────────────────────────────────────────────────────────

function emit(roots) {
  const tsc = findTsc(pkgDir)
  if (!tsc) fail('could not find tsc — run bun install at the workspace root')

  const tmp  = mkdtempSync(join(tmpdir(), 'emit-types-'))
  const copy = join(tmp, 'pkg')
  const out  = join(tmp, 'out')

  try {
    cpSync(pkgDir, copy, { recursive: true, filter: src => !SKIP.has(basename(src)) })
    for (const file of walk(copy)) if (isGenerated(file)) rmSync(file)
    // The node_modules tsc came from, for bun-types: without node's modules a
    // re-export from 'fs' emits as nothing, and litestone's #host loses half
    // its names to every importer.
    symlinkSync(dirname(dirname(tsc)), join(tmp, 'node_modules'), 'dir')

    // --noCheck: a `// @ts-check` file's type errors are its typecheck's to
    // report, not a reason to withhold its declarations.
    const run = spawnSync(tsc, [
      '--allowJs', '--declaration', '--emitDeclarationOnly', '--skipLibCheck', '--noCheck',
      '--types', 'bun-types',
      '--target', 'ESNext', '--module', 'Preserve', '--moduleResolution', 'bundler',
      '--newLine', 'lf', '--rootDir', '.', '--outDir', out,
      ...roots,
    ], { cwd: copy, encoding: 'utf8' })

    if (run.status !== 0) fail(`tsc failed:\n${run.stdout}${run.stderr}`)

    const files = new Map()
    for (const file of walk(out)) {
      const rel = relative(out, file)
      const src = './' + basename(rel).replace(/\.d\.ts$/, '.js')
      // tsc copies a bin's #! line into its declaration, and below the header
      // it is a syntax error in every app that imports it.
      const body = readFileSync(file, 'utf8').replace(/^#!.*\n/, '')
      files.set(rel, `${HEADER} from ${src} — edit the JS and run bun run types.\n${body}`)
    }
    return files
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}

// ─── comparing and writing ───────────────────────────────────────────────────

function compare(emitted) {
  for (const [rel, text] of emitted) {
    const file = join(pkgDir, rel)
    if (isHandWritten(file)) {
      problems.push(`${rel} is hand-written and would be overwritten by the emit — give it the import its JS needs, or delete it`)
      continue
    }
    if (existsSync(file) && readFileSync(file, 'utf8') === text) continue
    if (check) {
      problems.push(`${rel} ${existsSync(file) ? 'drifted from its JS' : 'is missing'} — run bun run types`)
      continue
    }
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, text)
    console.log(`  wrote ${rel}`)
  }

  for (const file of walk(pkgDir)) {
    const rel = relative(pkgDir, file)
    if (emitted.has(rel) || !isGenerated(file)) continue
    if (check) {
      problems.push(`${rel} is generated but no export reaches it any more — run bun run types`)
      continue
    }
    rmSync(file)
    console.log(`  removed ${rel}`)
  }
}

function report() {
  if (problems.length === 0) {
    if (check) console.log(`[types] ${pkg.name}: declarations match their JS`)
    return
  }
  console.error(`[types] ${pkg.name}:\n${problems.map(p => `  ✗ ${p}`).join('\n')}`)
  process.exit(1)
}

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue
    const path = join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(path)
    else if (entry.name.endsWith('.d.ts')) yield path
  }
}

function fail(message) {
  console.error(`[types] ${message}`)
  process.exit(2)
}
