import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', headless: true })
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } })
const errors = []
page.on('pageerror', e => errors.push('PAGE ERROR: ' + e.message))
page.on('dialog', d => d.type() === 'prompt' ? d.accept('my saved query') : d.accept())
const ok = (name, cond) => console.log((cond ? 'ok ' : 'FAIL ') + name)

await page.goto('http://127.0.0.1:5901/', { waitUntil: 'networkidle' })

ok('tenants nav visible', await page.locator('#navTenants').isVisible())
await page.click('#navTenants')
await page.waitForTimeout(800)
const tRows = await page.locator('#tenantList tbody tr').count()
ok('tenant list renders', tRows === 3)
await page.locator('#tenantList button:has-text("Open in Studio")').first().click()
await page.waitForTimeout(800)
ok('tenant badge shows', (await page.textContent('#tenantBadge')).includes('acme'))
await page.click('[data-table="user"]')
await page.waitForTimeout(700)
const tenantEmails = await page.locator('#dataGrid td[data-col="email"]').allTextContents()
ok('browse shows tenant data only', tenantEmails.length === 1 && tenantEmails[0].includes('admin@acme.com'))
await page.click('#tenantBadge')
await page.waitForTimeout(800)
ok('back to base', (await page.locator('#dataGrid tbody tr').count()) >= 6)

await page.locator('#dataGrid tbody tr').first().click()
await page.waitForTimeout(200)
await page.click('#btnRowDetail')
await page.waitForTimeout(800)
const drawer = await page.textContent('#rowDrawer')
ok('drawer shows record + relations', drawer.includes('Record') && drawer.includes('Belongs to') && drawer.includes('Referenced by'))
ok('drawer shows parent account', drawer.includes('accounts'))
await page.keyboard.press('Escape')
await page.waitForTimeout(200)
ok('Esc closes drawer', !(await page.locator('#rowDrawer').isVisible()))

await page.click('#navQuery')
await page.waitForTimeout(400)
await page.fill('#sqlEditor', 'SELECT COUNT(*) AS n FROM users')
await page.click('button:has-text("☆ Save")')
await page.waitForTimeout(600)
await page.click('button:has-text("▶ Run")')
await page.waitForTimeout(600)
const savedOpts = await page.locator('#savedQuerySel option').allTextContents()
ok('saved query listed', savedOpts.some(o => o.includes('my saved query')))
ok('history recorded', (await page.locator('#sqlHistorySel option').count()) >= 2)

await page.click('#navLite')
await page.waitForTimeout(900)
const src = await page.inputValue('#liteEditor')
await page.fill('#liteEditor', src.replace('model User {', 'model User {\n  tier      String?'))
await page.waitForTimeout(1800)
ok('live diff appears for edit', await page.locator('#liteDiff').isVisible())
ok('diff mentions user alter', (await page.textContent('#liteDiff')).includes('user'))

await page.click('#navSchema')
await page.waitForTimeout(900)
const dl = page.waitForEvent('download', { timeout: 5000 }).catch(() => null)
await page.click('button:has-text("⬇ SVG")')
const download = await dl
ok('ER SVG export downloads', !!download && (await download.suggestedFilename()) === 'schema-diagram.svg')

console.log(errors.length ? '\nJS ERRORS:\n' + errors.join('\n') : '\nNo JS errors')
await browser.close()
process.exit(errors.length ? 1 : 0)
