// ddl-snapshot.js — schema → the DDL SQLite is actually given, as a committed file
//
// The access snapshot's sibling, for the opposite problem. Access is a rule
// nothing below the API can show you; DDL is a name every app binds to. Columns
// are emitted verbatim camelCase and DateTime as ISO-8601 TEXT, so a change in
// the emitter renames a column in an app that never touched its schema — and no
// suite in that app can see it, because its own tests go through the client that
// changed with it.
//
// Rendered by `litestone ddl`, byte-compared by `litestone ddl --check`.
// Never imported by production code.

import { generateDDLForDatabase } from '../core/ddl.js'

const WIDTH = 76

function rule(label) {
  const head = `-- ─── ${label} `
  return head + '─'.repeat(Math.max(3, WIDTH - head.length))
}

const dbOf       = (model) => model.attributes.find(a => a.kind === 'db')?.name ?? 'main'
const isExternal = (model) => model.attributes.some(a => a.kind === 'external')

// ─── renderDdlSnapshot ────────────────────────────────────────────────────────
//
// One section per DECLARED database, in declaration order, so a database that
// gained models is a section that grew rather than a file that reordered. A
// driver with no tables is named and skipped: absent DDL and an absent database
// have to read differently.

export function renderDdlSnapshot(schema, { source = 'schema.lite', pluralize = false } = {}) {
  const databases = schema.databases?.length
    ? schema.databases
    : [{ name: 'main', driver: 'sqlite' }]

  const out = []

  out.push('-- Schema snapshot — DDL')
  out.push('--')
  out.push(`-- generated by: litestone ddl --schema ${source}${pluralize ? ' --pluralize' : ''}`)
  out.push('--')
  out.push('-- The DDL this schema emits — the tables, indexes, triggers and views a fresh')
  out.push('-- database is given. Do not edit; regenerate and read the diff. Columns are')
  out.push('-- emitted verbatim camelCase and DateTime as ISO-8601 TEXT, so hand-written SQL')
  out.push('-- binds to exactly these names and nothing else in an app can see one move.')
  out.push('-- Fragments an app merges at runtime are not in this file.')
  out.push('--')
  out.push(`-- ${schema.models.length} model${schema.models.length === 1 ? '' : 's'}` +
           ` · ${databases.length} database${databases.length === 1 ? '' : 's'}`)
  out.push('')

  for (const database of databases) {
    const driver = database.driver ?? 'sqlite'
    const models = schema.models.filter(m => dbOf(m) === database.name)

    out.push(rule(`database ${database.name} · ${driver}`))

    if (driver !== 'sqlite') {
      // jsonl and logger have no tables at all — an empty section here would
      // read as "litestone stopped emitting these".
      out.push(`-- No DDL — a ${driver} database has no schema. ${models.length} model(s)` +
               (models.length ? `: ${models.map(m => m.name).join(', ')}` : ''))
      out.push('')
      continue
    }

    const external = models.filter(isExternal)
    if (external.length)
      out.push(`-- @@external, managed outside litestone: ${external.map(m => m.name).join(', ')}`)

    if (!models.length) {
      out.push('-- No models declare this database.')
      out.push('')
      continue
    }

    const ddl = generateDDLForDatabase(schema, database.name, { foreignKeys: true, pluralize }).trim()
    out.push(ddl ? ddl : '-- Every model on this database is @@external — no DDL.')
    out.push('')
  }

  return out.join('\n').replace(/\n+$/, '\n')
}
