// catalog-snapshot.js — the .lite language surface as a committed file
//
// `test/catalog.test.ts` proves the catalog is COMPLETE: every word the parser
// accepts has a row. That is a different question from what a reviewer needs,
// which is *what changed* — a word whose arity gained an argument, an attribute
// that stopped being legal inside a type, a tokenizer that appeared. All of
// those keep the suite green, because the suite grades the table against the
// parser and both move together in one commit.
//
// So this renders the surface as something a person can diff, and the CI
// snapshots phase byte-compares it. What it deliberately does NOT carry is the
// blurbs: prose churns on wording, and a snapshot that reshuffles on an edited
// sentence is one nobody reads. Every column here is a fact another reader
// consumes — a name, where it is legal, what it accepts.
//
// Rendered by `litestone catalog --snapshot`, byte-compared by `--check`.
// Never imported by production code.

import { CATALOG, TOP_LEVEL, FIELD_ATTRS, MODEL_ATTRS, GROUPS, POSITIONS,
         POSITION_RULES, positionsOf, typed } from '../core/catalog.js'
import { VISIBILITY, PER_CALLER, RULES } from '../core/advise.js'

const esc = s => String(s).replace(/\|/g, '\\|')

/** `driver: sqlite · jsonl · logger`, or blank. */
function valuesCell(row) {
  if (!row.values) return ''
  return row.values.map(v =>
    `${v.arg}: ${v.of.map(e => typeof e === 'string' ? e : e.value).join(' · ')}`).join('<br>')
}

/**
 * Where a word is legal, when that is not the ordinary answer for its level.
 *
 * The ordinary case renders blank on purpose: a column repeating the same three
 * positions on fifty rows hides the four that differ, which are the only rows
 * this line exists for.
 */
const ORDINARY = { field: 3, model: 2 }

function positionsCell(row) {
  const all = positionsOf(row)
  if (all.length === ORDINARY[row.level]) return ''
  return all.map(p => POSITIONS[p] ?? p).join(' · ')
}

export function renderCatalogSnapshot() {
  const out = []
  const push = (...l) => out.push(...l)

  push('# Litestone language surface', '')
  push('<!-- generated by: litestone catalog --snapshot -->', '')
  push('Generated by `litestone catalog --snapshot`. **Do not edit.**', '')
  push('Every word a `.lite` file can hold, with where it is legal and what its',
       'arguments accept. The completeness of this table is asserted against the',
       'parser by `test/catalog.test.ts`; this file is the other question — what',
       'changed. Blurbs are deliberately absent: prose churns on wording, and a',
       'snapshot that reshuffles on an edited sentence is one nobody reads.', '')
  push(`**${CATALOG.length} words** — ${TOP_LEVEL.length} declarations · ` +
       `${FIELD_ATTRS.length} field attributes · ${MODEL_ATTRS.length} model attributes.`, '')

  push('## Declarations', '')
  push('| word | arity | accepts |', '| --- | --- | --- |')
  for (const r of TOP_LEVEL)
    push(`| \`${esc(r.word)}\` | ${esc(r.arity)} | ${valuesCell(r)} |`)
  push('')

  for (const [rows, title] of [[FIELD_ATTRS, 'Field attributes'], [MODEL_ATTRS, 'Model attributes']]) {
    push(`## ${title}`, '')
    push('| word | group | arity | legal | accepts | notes |', '| --- | --- | --- | --- | --- | --- |')
    for (const r of rows) {
      const notes = [
        r.removed    ? `**removed** — use \`${r.replacedBy}\`` : '',
        r.kind       ? `parses as \`${r.kind}\`` : '',
        r.excludes?.length ? `excludes ${r.excludes.join(', ')}` : '',
      ].filter(Boolean).join('; ')
      push(`| \`${esc(typed(r))}\` | ${esc(GROUPS[r.group] ?? r.group)} | ${esc(r.arity)} | ` +
           `${positionsCell(r)} | ${valuesCell(r)} | ${notes} |`)
    }
    push('')
  }

  push('## Positions', '')
  push('Which switch parses a word is not the same question as where it is legal.',
       'A blank `legal` column above means the ordinary answer for that level.', '')
  push('| position | refuses |', '| --- | --- |')
  for (const [pos, rule] of Object.entries(POSITION_RULES))
    push(`| ${esc(POSITIONS[pos] ?? pos)} | ${rule.only
      ? `everything except ${rule.only.map(w => `\`@${w}\``).join(', ')}`
      : rule.excludes.map(w => `\`${w}\``).join(', ')} |`)
  push('')

  push('## The visibility table', '')
  push('Three answers, one word. Asked as an interview in Studio.', '')
  push('| column | caller writes | caller reads | word |', '| --- | --- | --- | --- |')
  for (const r of VISIBILITY)
    push(`| ${r.stored ? 'yes' : 'no'} | ${r.callerWrites ? 'yes' : 'no'} | ` +
         `${r.callerReads ? 'yes' : 'no'} | ${r.word ? `\`@${r.word}\`` : `*${esc(r.answer)}*`} |`)
  push(`| — | — | depends who asks | \`${esc(PER_CALLER.answer)}\` |`, '')

  push('## Rules', '')
  push('Shapes the parser accepts and something later refuses.', '')
  push('| id | severity | title |', '| --- | --- | --- |')
  for (const r of RULES)
    push(`| \`${esc(r.id)}\` | ${r.severity} | ${esc(r.title)} |`)
  push('')

  return out.join('\n')
}
