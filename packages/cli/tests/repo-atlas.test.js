// repo-atlas.test.js — the deck, and what each plate is allowed to claim.
//
// The atlas is the same model `repo-map.js` collects, arranged. What is worth
// testing is the arrangement that could be WRONG rather than merely ugly: a
// dossier showing another package's issues, a dependency chip pointing at a
// card that is not in the deck, a filing convention the crossing does not
// understand. A misdrawn icon is cosmetic; a misattributed defect is a lie
// about who owns it.

import { describe, test, expect, beforeAll, afterAll } from 'bun:test'
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'fs'
import { join }   from 'path'
import { tmpdir } from 'os'

import { collect }                     from '../core/repo-map.js'
import { cards, actions, renderAtlas } from '../core/repo-atlas.js'

let ROOT

// The page carries two stylesheets — the vendored package and its own — so
// "the local CSS" is a claim about which BLOCK, not which position. Slicing at
// the first `<style>` used to mean the local one and now means the bundle, and
// a `not.toMatch` against the wrong slice passes for the wrong reason.
function localStyle(html) {
  const at = html.indexOf('<style id="atlas">')
  if (at === -1) throw new Error('no local stylesheet in the page')
  return html.slice(at, html.indexOf('</style>', at))
}

function workspace(name, extra = {}) {
  const dir = join(ROOT, name)
  const files = {
    'package.json': JSON.stringify({ name: 'ws', scripts: { ci: 'node scripts/ci.mjs' } }),
    'CLAUDE.md': [
      '# Map',
      '',
      '| Package | Realm/Domain | What it is | State |',
      '| --- | --- | --- | --- |',
      '| litestone | Data / D2 | The `.lite` language and its client | v1.1.0 · green |',
      '| sierra | UI meta | File-tree routing and the build | green |',
      '| cli (`fli`) | D1 | The command runtime | green |',
      '',
    ].join('\n'),
    'packages/litestone/package.json': JSON.stringify({ name: '@x/litestone', version: '1.0.0', scripts: { test: 'bun test' } }),
    'packages/sierra/package.json':    JSON.stringify({ name: '@x/sierra', version: '0.1.0', dependencies: { '@x/litestone': 'workspace:*' } }),
    'packages/cli/package.json':       JSON.stringify({ name: '@x/cli', version: '0.1.0' }),
    'packages/sierra/db/routes.snapshot.md': '<!-- generated by: sierra routes --config config/sierra.config.js -->\n',
    'ISSUES.md': [
      '# Issues',
      '',
      '## S2 — high',
      '',
      '| Id | Pkg | Title | Status | Verified | Detail |',
      '| --- | --- | --- | --- | --- | --- |',
      '| FJS-100 | litestone | **A gate refuses, a policy filters** | open | 2026-08-14 | — |',
      '| FJS-200 | cli/auth | **One defect filed against two packages** | open | 2026-08-14 | — |',
      '| FJS-300 | repo | **Something with no package** | open | 2026-08-14 | — |',
      '',
    ].join('\n'),
    ...extra,
  }

  for (const [path, body] of Object.entries(files)) {
    const full = join(dir, path)
    mkdirSync(join(full, '..'), { recursive: true })
    writeFileSync(full, body)
  }
  return collect({ root: dir })
}

const byKey = (deck, key) => deck.find(c => c.key === key)

beforeAll(() => { ROOT = mkdtempSync(join(tmpdir(), 'fli-repo-atlas-')) })
afterAll(()  => { try { rmSync(ROOT, { recursive: true, force: true }) } catch {} })

// ─── the deck ─────────────────────────────────────────────────────────────────

describe('the deck', () => {

  test('a plate carries the realm and the claim the root table states', () => {
    const deck = cards(workspace('deck'))
    const lite = byKey(deck, 'litestone')

    expect(lite.sub).toBe('Data / D2')
    expect(lite.bucket).toBe('data')
    expect(lite.blurb).toBe('The .lite language and its client')
  })

  test('the workspace gets a plate, because the register files things against it', () => {
    const deck = cards(workspace('deck-ws'))
    expect(byKey(deck, 'repo').kind).toBe('workspace')
  })

  test('an app is dealt as an app — a schema or a drive, never published', () => {
    const model = workspace('deck-app', {
      'example/package.json': JSON.stringify({ name: 'example', scripts: { verify: 'node verify.mjs' } }),
      'example/db/schema.lite': 'model Post {\n  id String @id\n}\n',
    })
    expect(byKey(cards(model), 'example').bucket).toBe('app')
  })

  test('a claimed folder is dealt last — a plan is not a part', () => {
    const model = workspace('deck-claimed', { 'packages/toolbelt/README.md': '# planned\n' })
    const deck  = cards(model)
    expect(deck[deck.length - 1].key).toBe('toolbelt')
    expect(deck[deck.length - 1].bucket).toBe('claimed')
  })

  test('plate numbers are positions and every one is unique', () => {
    const deck = cards(workspace('deck-plates'))
    expect(new Set(deck.map(c => c.plate)).size).toBe(deck.length)
    expect(deck[0].plate).toBe('01')
  })

  test('a package the root table never names still gets a plate', () => {
    const model = workspace('deck-unfiled', {
      'packages/orphan/package.json': JSON.stringify({ name: '@x/orphan', version: '0.0.1' }),
    })
    const card = byKey(cards(model), 'orphan')
    expect(card.sub).toBe('unfiled')
    expect(card.bucket).toBe('other')
  })
})

// ─── the crossings ────────────────────────────────────────────────────────────

describe('what a dossier claims', () => {

  test('an issue lands on the package it names, and nowhere else', () => {
    const html = renderAtlas(workspace('cross-issue'))
    const lite = dossierOf(html, 'litestone')
    const cli  = dossierOf(html, 'cli')

    expect(lite).toContain('FJS-100')
    expect(cli).not.toContain('FJS-100')
  })

  test('a row filed against two packages shows on both, not neither', () => {
    const html = renderAtlas(workspace('cross-both'))
    expect(dossierOf(html, 'cli')).toContain('FJS-200')
    expect(dossierOf(html, 'auth') ?? dossierOf(html, 'cli')).toContain('FJS-200')
  })

  test('a row filed against no package lands on the workspace plate', () => {
    const html = renderAtlas(workspace('cross-repo'))
    expect(dossierOf(html, 'repo')).toContain('FJS-300')
    expect(dossierOf(html, 'litestone')).not.toContain('FJS-300')
  })

  test('a snapshot belongs to the directory that holds it', () => {
    const html = renderAtlas(workspace('cross-snap'))
    expect(dossierOf(html, 'sierra')).toContain('routes.snapshot.md')
    expect(dossierOf(html, 'litestone')).not.toContain('routes.snapshot.md')
  })

  test('a dependency chip only links where the deck holds that card', () => {
    const html = renderAtlas(workspace('cross-chip'))
    // Every href the page writes for a card must name a dossier it rendered,
    // or the page is a dead end at exactly the moment it is being used. A route
    // may carry a facet — `part/repo/S2` — and then it is the HEAD that has to
    // name one, with the tail a facet that dossier offers.
    const targets  = [...html.matchAll(/href="#\/([^"]+)"/g)].map(m => m[1])
    const rendered = [...html.matchAll(/data-dossier="([^"]+)"/g)].map(m => m[1])
    const offered  = [...html.matchAll(/data-value="([^"]*)"/g)].map(m => m[1])
    expect(targets.length).toBeGreaterThan(0)
    for (const t of targets) {
      if (rendered.includes(t)) continue
      // A route splits at the SECOND slash — a facet value may hold one.
      const parts = t.split('/')
      expect(rendered).toContain(parts.slice(0, 2).join('/'))
      const facet = decodeURIComponent(parts.slice(2).join('/'))
      expect(offered).toContain(facet.slice(facet.indexOf(':') + 1))
    }
  })
})

