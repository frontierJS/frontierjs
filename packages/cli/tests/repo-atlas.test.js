// ─── the page ─────────────────────────────────────────────────────────────────

describe('the page', () => {

  test('renders one file for one tree — it is committed and rechecked', () => {
    expect(renderAtlas(workspace('page-a'))).toBe(renderAtlas(workspace('page-a')))
  })

  test('names its own generator where the snapshot walker reads it', () => {
    const html = renderAtlas(workspace('page-gen'))
    expect(html.split('\n').slice(0, 2)).toEqual(['<!doctype html>', '<!-- generated by: fli ws:atlas -->'])
  })

  test('writes no color of its own — a tone carries the meaning', () => {
    // Invariant 13. A hex here is a theme that stops working: the nine themes
    // move tokens, and a literal moves with none of them.
    const html  = renderAtlas(workspace('page-tones'))
    const local = localStyle(html)
    // A theme is the one place a color is written; everywhere else reads a
    // token, or the nine themes stop reaching it.
    const outsideTheme = local.replace(/\.theme-field\{[\s\S]*?\n\}/, '')

    expect(outsideTheme).not.toMatch(/#[0-9a-fA-F]{3}\b|#[0-9a-fA-F]{6}\b|rgba?\(|hsla?\(/)
    expect(html).toContain('badge danger')
  })

  test('a realm accent is derived from the tone tokens, never picked', () => {
    // Identity is a second axis the vocabulary has no word for, so the atlas
    // adds one — out of the tokens, so every theme still moves all nine.
    const html  = renderAtlas(workspace('page-realms'))
    const local = localStyle(html)

    for (const bucket of ['data', 'api', 'ui', 'testing', 'tooling', 'cross', 'app', 'other', 'claimed'])
      expect(local).toContain(`.b-${bucket}{--realm:`)

    // Every accent resolves through a token — a literal would survive no theme.
    // A theme may name the nine outright; anything else falls back to a tone.
    for (const [, value] of local.matchAll(/\.b-[a-z]+\{--realm:([^}]+)\}\n/g))
      expect(value).toContain('var(--color-')
  })

  // A css package small enough to assert against, laid out the way the real
  // one is: an order declaration, layered imports, and a comment to strip.
  const CSS_SRC = {
    'packages/css/src/index.css': [
      '@layer reset, tokens, themes, components;',
      "@import './foundation/reset.css'  layer(reset);",
      "@import './foundation/tokens.css' layer(tokens);",
      "@import './themes/field.css'      layer(themes);",
      "@import './components/buttons.css' layer(components);",
      '',
    ].join('\n'),
    'packages/css/src/foundation/reset.css': 'a:where([class]){text-decoration:none}\n',
    'packages/css/src/foundation/tokens.css': '/* the ladder */\n:root{--space-sm:0.5rem}\n',
    'packages/css/src/themes/field.css': '.theme-field{--surface:#141210}\n',
    'packages/css/src/components/buttons.css': '.btn{padding:var(--space-sm);content:"/* not a comment */"}\n',
  }

  test('inlines the styling language instead of fetching it', () => {
    // The page opens from a file:// path and a published Artifact is refused
    // an external request by CSP, so a link is a page that does not render.
    const html = renderAtlas(workspace('page-css-inline', CSS_SRC))

    expect(html).toContain('<style id="fjs-css">')
    expect(html).not.toContain('unpkg.com')
    expect(html).toContain('.btn{padding:var(--space-sm)')
  })

  test('the vendored bundle declares layer order first, and wraps each import', () => {
    // Without the declaration, order falls back to first appearance — which
    // agrees with the declaration only by accident of import order. Measured in
    // packages/css/build.js: move the utilities import up and `.btn.text-lg`
    // goes 16px to 14px in the bundle while the source stays 16px.
    const html   = renderAtlas(workspace('page-css-order', CSS_SRC))
    const bundle = html.slice(html.indexOf('<style id="fjs-css">'), html.indexOf('</style>'))

    expect(bundle.indexOf('@layer reset, tokens, themes, components;'))
      .toBeLessThan(bundle.indexOf('@layer reset {'))
    for (const layer of ['reset', 'tokens', 'themes', 'components'])
      expect(bundle).toContain(`@layer ${layer} {`)
  })

  test('the vendored bundle drops comments and keeps strings that look like them', () => {
    // Comments are ~60% of that package's source and none of it is read here.
    // A stripper that is right by luck is one nobody can safely edit, so the
    // quote case is asserted rather than assumed absent.
    const html   = renderAtlas(workspace('page-css-strip', CSS_SRC))
    const bundle = html.slice(html.indexOf('<style id="fjs-css">'), html.indexOf('</style>'))

    expect(bundle).not.toContain('the ladder')
    expect(bundle).toContain('content:"/* not a comment */"')
  })

  test('a workspace with no styling language falls back to the link', () => {
    // The fallback exists for a tree that cannot read the package at all. For a
    // committed snapshot that never happens, which is what stops the two
    // outputs swapping places on one tree.
    const html = renderAtlas(workspace('page-css-absent'))

    expect(html).toContain('unpkg.com/@frontierjs/css/dist/frontier.min.css')
    expect(html).not.toContain('<style id="fjs-css">')
    // field.css lives in the workspace copy, so the published bundle may not
    // carry the theme yet and the page must not offer it.
    expect(html).not.toContain('<option value="field"')
  })

  test('links the styling language with no version range at all', () => {
    // The range used to be DERIVED from the workspace's own copy, on the
    // reasoning that an exact pin 404s because the local version runs ahead of
    // the published one. A caret does not fix that below 1.0, it hides it:
    // `^0.16` means `>=0.16.0 <0.17.0`, so the moment the tree bumped its minor
    // the link named a version the registry has never had and the page rendered
    // as unstyled markup. Measured that day: `@^0.16` 404, no range 302.
    //
    // So the workspace version must not reach the URL at all — asserted with a
    // version deliberately ahead of anything published.
    const model = workspace('page-css', {
      'packages/css/package.json': JSON.stringify({ name: '@frontierjs/css', version: '9.9.9' }),
    })
    const html = renderAtlas(model)
    expect(html).toContain('unpkg.com/@frontierjs/css/dist/frontier.min.css')
    expect(html).not.toContain('@frontierjs/css@')
  })

  test('offers every theme the styling language ships', () => {
    const html = renderAtlas(workspace('page-themes'))
    for (const theme of ['default', 'dark', 'midnight', 'forest', 'sunset', 'elite', 'basecamp', 'notebook', 'press'])
      expect(html).toContain(`<option value="${theme}"`)
  })

  test('every dossier carries its own search box', () => {
    // A dossier is long — litestone's runs to ninety-odd searchable units — and
    // the deck's box narrows the deck, not what is inside a sheet.
    const html   = renderAtlas(workspace('page-search'))
    const sheets = [...html.matchAll(/data-dossier="/g)].length
    // The rendered inputs, not the selectors the page's own script names.
    const boxes  = [...html.matchAll(/<input[^>]*data-dsearch/g)].length
    expect(boxes).toBe(sheets)
    expect(html).toContain('data-dcount')
  })

  test('escapes the prose it quotes', () => {
    const model = workspace('page-esc', {
      'ISSUES.md': '# Issues\n\n## S2 — high\n\n| Id | Pkg | Title | Status | Verified | Detail |\n| --- | --- | --- | --- | --- | --- |\n| FJS-9 | sierra | **A `<script>` in a claim** | open | 2026-08-14 | — |\n',
    })
    expect(renderAtlas(model)).toContain('&lt;script&gt;')
  })
})

/** The dossier for one card, as rendered — everything between its marker and the next. */
function dossierOf(html, key) {
  // Routes are namespaced (`part/…`, `do/…`); a bare key means a part.
  const start = html.indexOf(`data-dossier="${key.includes('/') ? key : `part/${key}`}"`)
  if (start < 0) return null
  // A dossier is a <dialog>; the next one begins where this one ends.
  const end = html.indexOf('<dialog', start + 1)
  return html.slice(start, end < 0 ? undefined : end)
}
