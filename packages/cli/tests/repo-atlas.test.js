describe('search by action', () => {

  const withRunnables = (name) => workspace(name, {
    'package.json': JSON.stringify({ name: 'ws', scripts: { build: 'bun run --filter * build' } }),
    'packages/cli/commands/deploy/local.md': '---\ntitle: deploy:local\ndescription: Build the image and boot it\n---\n',
    'example/package.json': JSON.stringify({ name: 'example', scripts: { verify: 'node test/verify.mjs' } }),
    'example/db/schema.lite': 'model Post {\n  id String @id\n}\n',
  })

  test('an action gathers commands, scripts, drives and generators alike', () => {
    const deploying = actions(withRunnables('act-pool')).find(a => a.name === 'deploying')
    expect(deploying.hits.map(h => h.label)).toContain('fli deploy:local')

    const testing = actions(withRunnables('act-drive')).find(a => a.name === 'testing')
    expect(testing.hits.some(h => h.kind === 'drive')).toBe(true)
  })

  test('an action nothing answers to is not offered', () => {
    // The vocabulary is curated; the membership is not. A word with no hit in
    // this workspace would be a door onto an empty room.
    const model = workspace('act-empty')
    const names = actions(model).map(a => a.name)
    for (const name of names) expect(actions(model).find(a => a.name === name).hits.length).toBeGreaterThan(0)
  })

  test('every action term on the page has a sheet behind it', () => {
    const html = renderAtlas(withRunnables('act-sheets'))
    const terms  = [...html.matchAll(/data-action="([^"]+)"/g)].map(m => m[1])
    const sheets = [...html.matchAll(/data-dossier="do\/([^"]+)"/g)].map(m => m[1])
    expect(terms.length).toBeGreaterThan(0)
    for (const t of terms) expect(sheets).toContain(t)
  })
})

describe('search by realm', () => {

  test('every realm term matches plates that carry that bucket', () => {
    const html = renderAtlas(workspace('realm-terms'))
    const terms   = [...html.matchAll(/data-realm="([^"]*)"/g)].map(m => m[1]).filter(Boolean)
    const buckets = [...html.matchAll(/data-bucket="([^"]+)"/g)].map(m => m[1])
    expect(terms.length).toBeGreaterThan(0)
    for (const t of terms) expect(buckets).toContain(t)
  })
})

