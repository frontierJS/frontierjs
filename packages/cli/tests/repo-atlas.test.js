describe('the palette', () => {

  const corpusOf = (html) => JSON.parse(
    html.match(/id="atlas-corpus">([\s\S]*?)<\/script>/)[1].replace(/\\u003c/g, '<'))

  test('indexes every kind of noun the page holds', () => {
    const model = workspace('pal-kinds', {
      'packages/cli/commands/db/seed.md': '---\ntitle: db:seed\ndescription: Run the seeder\n---\n',
      'packages/litestone/docs/encryption.md': '# Encryption\n\nSealed at the boundary.\n',
    })
    const kinds = new Set(corpusOf(renderAtlas(model)).map(row => row[0]))

    for (const kind of ['part', 'issue', 'topic', 'command', 'snapshot', 'register'])
      expect([...kinds]).toContain(kind)
  })

  test('every route it offers names a dossier the page rendered', () => {
    // A palette that lands nowhere is worse than no palette: it is confidently
    // wrong at the moment somebody is lost.
    const html     = renderAtlas(workspace('pal-routes'))
    const rendered = [...html.matchAll(/data-dossier="([^"]+)"/g)].map(m => m[1])

    for (const [, , , href] of corpusOf(html)) {
      if (!href.startsWith('#')) continue
      expect(rendered).toContain(href.replace(/^#\//, ''))
    }
  })

  test('an issue points at the plate that owns it', () => {
    const rows = corpusOf(renderAtlas(workspace('pal-issue')))
    const row  = rows.find(r => r[0] === 'issue' && r[1].startsWith('FJS-100'))
    expect(row[3]).toBe('#/part/litestone')
  })
})

