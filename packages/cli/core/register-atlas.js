// ─── helpers ──────────────────────────────────────────────────────────────────

function projectName(root) {
  try { return JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')).name || basename(root) }
  catch { return basename(root) }
}

function withoutLead(body, title) {
  return title && body.startsWith(title) ? body.slice(title.length).trim() : body
}

function rel(from, abs) {
  return relative(from, abs) || '.'
}

function editUrl(abs, line) {
  return `vscode://file${abs}${line ? `:${line}` : ''}`
}

function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

// Runs before the body is parsed, so a dark reader gets no white flash.
