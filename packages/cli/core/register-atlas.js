/** The page. `css` is the vendored stylesheet, or null to link the published one. */
export function renderRegisterAtlas(model, css = null) {
  const light = css ? THEME_LIGHT : FALLBACK.light
  const dark  = css ? THEME_DARK  : FALLBACK.dark
  const json  = JSON.stringify(model).replace(/</g, '\\u003c')
  const title = `${model.name} — registers`

  return [
    '<!doctype html>',
    // No `generated by:` line: the ranking reads git, so this is never a snapshot.
    '<!-- fli register:atlas · not a snapshot -->',
    `<html lang="en" class="theme-${light}"><head><meta charset="utf-8">`,
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${esc(title)}</title>`,
    css
      ? `<style id="fjs-css">${css}</style>`
      : `<link rel="stylesheet" href="${CDN_STYLESHEET}">`,
    `<style id="ratlas">${STYLE}</style>`,
    `<script>${headScript(light, dark)}</script>`,
    '</head><body class="app">',
    `<header class="topbar">
      <strong>${esc(model.name)}</strong>
      <span class="text-xs text-muted">${esc(model.prefix ?? 'no prefix')} · ${esc(model.dir)}</span>
      <input id="q" class="field" type="search" placeholder="filter this tab…  /" aria-label="Filter">
      <span class="pill" id="hits"></span>
      <label class="ra-theme"><span class="text-xs text-muted">theme</span>
        <select class="field" id="theme" aria-label="Theme">
          ${(css ? ['field', ...THEMES] : THEMES).map(t => `<option value="${t}">${t}</option>`).join('')}
        </select>
      </label>
    </header>`,
    '<main class="screen stack">',
    '<div id="warn"></div>',
    `<div class="tabs">
      <div class="tablist" role="tablist" aria-label="Registers">
        ${TABS.map(([key, label]) => `<a class="tab" role="tab" href="#/${key}" data-tab="${key}" aria-selected="false">${label} <span class="pill" data-count="${key}"></span></a>`).join('')}
      </div>
      <div class="cluster gap-2xs ra-facets" id="facets"></div>
      <article class="view stack" role="tabpanel" id="view"></article>
    </div>`,
    '</main>',
    `<footer class="bar"><span class="text-xs text-muted">fli register:atlas · regenerate, never commit</span></footer>`,
    `<script type="application/json" id="model">${json}</script>`,
    `<script>${SCRIPT}</script>`,
    '</body></html>',
    '',
  ].join('\n')
}

