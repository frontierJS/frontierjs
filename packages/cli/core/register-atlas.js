// ─── register-atlas.js — the registers as one page somebody works from ───────
//
// `fli register:atlas`. The three registers, the question queue and the
// ranking, crossed on one page for ANY project that declares `registers` in
// its package.json — a client app with `.project/` as much as this workspace.
// `ws:atlas` carries the registers too, but as a claim-only index inside a deck
// of package plates, and it needs a workspace to exist at all.
//
// ── What is read, and from where ─────────────────────────────────────────────
//
//   issues, rulings, ideas  ← core/registers.js `readRegisters`
//   the question queue      ← core/decisions.js `readDecisions`
//   ruling sections         ← core/decisions.js `rulingSections`
//   the ranking             ← core/next.js `rankNext`
//
// Nothing here parses a register file. A record this module cannot place is a
// defect in one of those readers, and fixing it there fixes `register:check`,
// `fli next` and the GUI in the same commit.
//
// ── Why the page is not a snapshot ───────────────────────────────────────────
//
// `rankNext` scores a row up when code it names was touched in recent commits,
// so two runs over one register differ by git history alone. The page carries
// no `generated by:` line and nothing gates it — regenerate it, never commit it.
//
// ── Links ────────────────────────────────────────────────────────────────────
//
// A link in a register is relative to the FILE it is written in — `../api/…`
// in `.project/ISSUES.md`, `../../web/…` in `.project/IDEAS/x.md` — so every
// one is resolved against its own file and then re-expressed relative to where
// the page is written. `edit` is an absolute `vscode://file/` URL with the
// line, which is the link that is actually clicked.

import { readFileSync }                         from 'node:fs'
import { dirname, relative, resolve, basename } from 'node:path'

import { readRegisters, registerLayout } from './registers.js'
import { readDecisions, rulingSections } from './decisions.js'
import { rankNext, blockedBy }           from './next.js'
import { THEMES, THEME_LIGHT, THEME_DARK, FALLBACK } from './terms.js'
import { CDN_STYLESHEET }                  from './assets.js'

// ─── collect ──────────────────────────────────────────────────────────────────

/**
 * The page's model. `outDir` is where the page will be written — every `href`
 * is relative to it. `touched` is handed to `rankNext`, for a test.
 */
export function collectRegisterAtlas(root, { outDir = null, touched = null } = {}) {
  const layout = registerLayout(root)
  const doc    = readRegisters(root)
  const out    = outDir ?? layout.dir

  const where = (file, line) => {
    const abs = resolve(root, file)
    return { file, line: line ?? null, href: rel(out, abs), edit: editUrl(abs, line) }
  }

  // A record's links are relative to the file that holds it.
  const links = (record) => (record.files ?? []).map(link => {
    const abs = resolve(dirname(resolve(root, record.file)), link.replace(/\/$/, ''))
    return { label: relative(root, abs) || '.', href: rel(out, abs), edit: editUrl(abs, null) }
  })

  const ranking = rankNext(root, { touched })
  const rank    = new Map()
  ranking.ready.forEach((r, i) => rank.set(r.id, { n: i + 1, score: r.score, terms: r.terms.map(t => t.note ?? t.term) }))
  for (const r of ranking.blocked) rank.set(r.id, { n: null, score: r.score, terms: r.terms.map(t => t.note ?? t.term) })

  const issues = doc.issues.map(r => ({
    id:        r.id,
    aliases:   r.aliases ?? [],
    pkg:       r.pkg ?? [],
    title:     r.title,
    status:    r.status,
    severity:  r.severity,
    verified:  r.verified ?? '',
    closed:    !!r.closed,
    // The reader flattens the whole row, so the body opens on the title.
    body:      withoutLead(r.body ?? '', r.title),
    refs:      (r.refs ?? []).filter(id => id !== r.id),
    blockedBy: r.closed ? [] : blockedBy(r),
    rank:      rank.get(r.id) ?? null,
    links:     links(r),
    at:        where(r.file, r.line),
  }))

  const rulings = doc.decisions.map(r => ({
    id:           r.id,
    date:         r.date ?? '',
    section:      r.section ?? '',
    title:        r.title ?? '',
    status:       r.status ?? '',
    supersededBy: r.supersededBy ?? null,
    body:         r.body ?? '',
    refs:         (r.refs ?? []).filter(id => id !== r.id),
    links:        links(r),
    at:           where(r.file, r.line),
  }))

  const questions = readDecisions(root).map(q => ({
    id:        q.id,
    source:    q.source,
    question:  q.question,
    state:     q.state,
    options:   q.options,
    recommend: q.recommend,
    paper:     q.paper?.id ?? null,
    at:        where(q.file, q.line),
  }))

  const asked = new Map()
  for (const q of questions) if (q.paper && q.state !== 'ruled') asked.set(q.paper, (asked.get(q.paper) ?? 0) + 1)

  const ideas = doc.ideas.map(r => ({
    id:        r.id,
    title:     r.title,
    status:    r.status,
    dated:     r.dated ?? '',
    body:      r.body ?? '',
    refs:      r.refs ?? [],
    questions: asked.get(r.id) ?? 0,
    links:     links(r),
    at:        where(r.file, r.line),
  }))

  return {
    name:       projectName(root),
    prefix:     doc.prefix,
    dir:        relative(root, layout.dir) || '.',
    sources:    doc.sources,
    unparsed:   doc.unparsed,
    duplicates: doc.ids.duplicates,
    sections:   rulingSections(root),
    ready:      ranking.ready.map(r => r.id),
    blocked:    ranking.blocked.map(r => r.id),
    issues,
    rulings,
    ideas,
    questions,
  }
}

