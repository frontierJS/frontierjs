// ─── script ───────────────────────────────────────────────────────────────────
//
// The page renders from the embedded model, so a register of 1,400 rows costs
// one JSON parse rather than 1,400 rows of markup in the file.

const SCRIPT = `
const M=JSON.parse(document.getElementById('model').textContent)
const $=id=>document.getElementById(id)
const view=$('view'),facets=$('facets'),q=$('q'),hits=$('hits')
const byId=new Map()
for(const r of M.issues){ byId.set(r.id.toLowerCase(),['issue',r]); for(const a of r.aliases) byId.set(a.toLowerCase(),['issue',r]) }
for(const r of M.rulings) if(r.id) byId.set(r.id.toLowerCase(),['ruling',r])
for(const r of M.ideas) byId.set(r.id.toLowerCase(),['idea',r])

${CLIENT_ESC}

// ── what each tab holds ──
const open=M.issues.filter(r=>!r.closed)
const SETS={
  next:    ()=>[...M.ready,...M.blocked].map(id=>byId.get(id.toLowerCase())?.[1]).filter(Boolean),
  decide:  ()=>M.questions.filter(x=>x.state!=='ruled'),
  issues:  ()=>open,
  rulings: ()=>M.rulings,
  ideas:   ()=>M.ideas,
  closed:  ()=>M.issues.filter(r=>r.closed),
}
for(const [k,f] of Object.entries(SETS)){ const el=document.querySelector('[data-count="'+k+'"]'); if(el) el.textContent=f().length }

// A facet is a dimension, a record's value for it, and the choices in file order.
const FACETS={
  issues:  [['severity',r=>r.severity],['area',r=>r.pkg],['status',r=>r.status]],
  closed:  [['area',r=>r.pkg]],
  rulings: [['section',r=>r.section],['status',r=>r.status||'in force']],
  ideas:   [['status',r=>r.status]],
  decide:  [['state',x=>x.state]],
  next:    [['severity',r=>r.severity],['area',r=>r.pkg]],
}
const picked={}

function drawFacets(tab){
  const dims=FACETS[tab]||[]
  facets.innerHTML=dims.map(([dim,get])=>{
    const seen=new Map()
    for(const r of SETS[tab]()) for(const v of [].concat(get(r)||[])) seen.set(v,(seen.get(v)||0)+1)
    if(seen.size<2) return ''
    const now=picked[tab+':'+dim]||''
    return '<label class="text-xs text-muted">'+dim+' <select class="field" data-dim="'+dim+'"><option value="">any</option>'
      +[...seen].map(([v,n])=>'<option value="'+esc(v)+'"'+(v===now?' selected':'')+'>'+esc(v)+' ('+n+')</option>').join('')
      +'</select></label>'
  }).join('')
  if(tab==='decide') facets.insertAdjacentHTML('beforeend',sectionPicker())
  for(const s of facets.querySelectorAll('[data-dim]')) s.addEventListener('change',()=>{ picked[tab+':'+s.dataset.dim]=s.value; draw() })
  const sec=facets.querySelector('#section')
  if(sec) sec.addEventListener('change',()=>{ try{ localStorage.setItem('fli.registers.section',sec.value) }catch{}; draw() })
}

function sectionPicker(){
  if(!M.sections.length) return ''
  let saved=''; try{ saved=localStorage.getItem('fli.registers.section')||'' }catch{}
  return '<label class="text-xs text-muted">file rulings under <select class="field" id="section">'
    +M.sections.map(s=>'<option'+(s===saved?' selected':'')+'>'+esc(s)+'</option>').join('')+'</select></label>'
}

// ── rows ──
const tone=s=>s==='S1'||s==='S2'?'danger':s==='S3'?'warning':s==='decision'?'info':'muted'
const ideaTone=s=>s==='shipped'?'success':s==='partial'?'info':s==='withdrawn'||s==='superseded-by'?'muted':'warning'

function refChips(refs){
  return refs.length?'<div class="cluster gap-2xs">'+refs.map(id=>byId.has(id.toLowerCase())
    ?'<a class="chip link" href="#/id/'+esc(id)+'">'+esc(id)+'</a>'
    :'<span class="chip">'+esc(id)+'</span>').join('')+'</div>':''
}
function linkChips(links){
  return links.length?'<div class="cluster gap-2xs">'+links.map(l=>'<a class="chip link" href="'+esc(l.edit)+'" title="open in editor">'+esc(l.label)+'</a>').join('')+'</div>':''
}
function source(at){
  return '<div class="text-xs text-muted"><a class="link" href="'+esc(at.edit)+'">edit '+esc(at.file)+(at.line?':'+at.line:'')+'</a> · <a class="link" href="'+esc(at.href)+'">view</a></div>'
}

function rowHead(lead,title,sub,tail){
  return '<summary><span class="ra-lead">'+lead+'</span>'
    +'<span class="ra-main"><span class="ra-title">'+title+'</span>'
    +(sub?'<span class="ra-sub text-xs text-muted">'+sub+'</span>':'')+'</span>'
    +'<span class="ra-tail">'+(tail||'')+'</span></summary>'
}

function issueRow(r){
  const rank=r.rank&&r.rank.n?'#'+r.rank.n:''
  return '<details class="ra-row" data-id="'+esc(r.id)+'">'
    +rowHead(
      '<span class="badge '+tone(r.severity)+'">'+esc(r.severity)+'</span><span class="ra-id">'+esc(r.id)+'</span>',
      esc(r.title),
      '<span>'+esc([].concat(r.pkg).join(', '))+' · '+esc(r.status)+(r.verified?' · '+esc(r.verified):'')+'</span>'
        +(r.blockedBy.length?'<span class="badge warning">blocked by '+esc(r.blockedBy.join(', '))+'</span>':''),
      rank?'<span class="pill">'+rank+'</span>':'')
    +'<div class="ra-body">'
    +(r.rank?'<div class="text-xs text-muted">score '+r.rank.score+' — '+esc(r.rank.terms.join(' · '))+'</div>':'')
    +'<p class="text-sm">'+esc(r.body)+'</p>'+refChips(r.refs)+linkChips(r.links)+source(r.at)+'</div></details>'
}

function rulingRow(r){
  return '<details class="ra-row" data-id="'+esc(r.id||'')+'">'
    +rowHead(
      r.id?'<span class="badge info">'+esc(r.id)+'</span>':'',
      esc(r.title),
      '<span>'+esc([r.date,r.section].filter(Boolean).join(' · '))+'</span>'
        +(r.status?'<span class="badge muted">'+esc(r.status)+(r.supersededBy?' '+esc(r.supersededBy):'')+'</span>':''))
    +'<div class="ra-body"><p class="text-sm">'+esc(r.body)+'</p>'+refChips(r.refs)+linkChips(r.links)+source(r.at)+'</div></details>'
}

function ideaRow(r){
  return '<details class="ra-row" data-id="'+esc(r.id)+'">'
    +rowHead(
      '<span class="badge '+ideaTone(r.status)+'">'+esc(r.status||'?')+'</span>',
      esc(r.title),
      esc(r.id)+(r.dated?' · '+esc(r.dated):''),
      r.questions?'<a class="pill" href="#/decide/'+esc(r.id)+'" title="open questions">'+r.questions+' ?</a>':'')
    +'<div class="ra-body"><p class="text-sm">'+esc(r.body)+'</p>'+refChips(r.refs)+linkChips(r.links)+source(r.at)+'</div></details>'
}

// \`fli decide\` is the one writer, so the page hands out its exact command.
function decideCmd(x,letter){
  const sec=$('section')?.value||''
  const rec=x.recommend&&x.recommend.letter===letter&&!x.recommend.qualifier
  return 'fli decide '+x.id+' '+letter+(sec?' --section "'+sec.replace(/"/g,'\\\\"')+'"':'')+(rec?'':' --why ""')
}

function questionRow(x){
  const opts=x.options.map(o=>{
    const rec=x.recommend&&x.recommend.letter===o.letter
    return '<li class="'+(rec?'is-rec':'')+'"><strong>'+esc(o.letter)+'</strong> — '+esc(o.text)
      +' <button class="btn ghost" data-copy="'+esc(x.id)+'" data-letter="'+esc(o.letter)+'">copy fli decide</button></li>'
  }).join('')
  return '<details class="ra-row" data-id="'+esc(x.id)+'" data-paper="'+esc(x.paper||'')+'"'+(x.state==='decidable'?' open':'')+'>'
    +rowHead(
      '<span class="badge '+(x.state==='decidable'?'success':'muted')+'">'+esc(x.state)+'</span>',
      esc(x.question),
      esc(x.paper||x.source))
    +'<div class="ra-body">'
    +(opts?'<ul class="ra-opts dense">'+opts+'</ul>':'<p class="text-sm text-muted">No lettered options yet — write **A** / **B** sub-bullets and a **Recommend X** line to make it pickable.</p>')
    +(x.recommend?'<p class="text-sm">★ Recommend '+esc(x.recommend.qualifier||x.recommend.letter)+' — '+esc(x.recommend.why)+'</p>':'')
    +'<input class="field ra-cmd hidden" readonly>'
    +source(x.at)+'</div></details>'
}

const ROW={ next:issueRow, issues:issueRow, closed:issueRow, rulings:rulingRow, ideas:ideaRow, decide:questionRow }

// ── the view ──
let tab='next'
function draw(){
  const f=q.value.trim().toLowerCase()
  const dims=FACETS[tab]||[]
  let list=SETS[tab]()
  for(const [dim,get] of dims){
    const want=picked[tab+':'+dim]
    if(want) list=list.filter(r=>[].concat(get(r)||[]).includes(want))
  }
  if(f) list=list.filter(r=>JSON.stringify(r).toLowerCase().includes(f))
  const total=SETS[tab]().length
  hits.textContent=list.length===total?total:list.length+' / '+total
  view.innerHTML=list.length?list.map(ROW[tab]).join(''):'<div class="empty"><div class="empty-title">Nothing here</div><div class="empty-text">'+(total?'Nothing matches the filter.':'This register holds no records of this kind.')+'</div></div>'
}

function show(next,focus){
  tab=SETS[next]?next:'next'
  for(const t of document.querySelectorAll('[data-tab]')) t.setAttribute('aria-selected',String(t.dataset.tab===tab))
  drawFacets(tab)
  draw()
  if(focus) flash(focus)
}

function flash(key){
  const el=[...view.querySelectorAll('[data-id],[data-paper]')].find(d=>d.dataset.id===key||d.dataset.paper===key)
  if(!el) return
  el.open=true
  el.classList.add('is-flash')
  el.scrollIntoView({block:'center'})
  setTimeout(()=>el.classList.remove('is-flash'),1500)
}

// \`#/issues\` is a tab, \`#/id/ELA-004\` is a record wherever it lives, and
// \`#/decide/<paper>\` is a tab opened on that paper's questions.
function route(){
  const [head,...rest]=decodeURIComponent(location.hash.replace(/^#\\/?/,'')).split('/')
  const arg=rest.join('/')
  if(head==='id'){
    const hit=byId.get(arg.toLowerCase())
    if(!hit) return show(tab)
    const [kind,r]=hit
    q.value=''
    return show(kind==='ruling'?'rulings':kind==='idea'?'ideas':r.closed?'closed':'issues',r.id)
  }
  show(head||'next',arg||null)
}
addEventListener('hashchange',route)

q.addEventListener('input',draw)
addEventListener('keydown',e=>{
  if(e.key!=='/'||/^(input|textarea|select)$/i.test(e.target.tagName)) return
  e.preventDefault(); q.focus()
})

view.addEventListener('click',async e=>{
  const b=e.target.closest('[data-copy]')
  if(!b) return
  e.preventDefault()
  const x=M.questions.find(y=>y.id===b.dataset.copy)
  const cmd=decideCmd(x,b.dataset.letter)
  const box=b.closest('.ra-body').querySelector('.ra-cmd')
  box.value=cmd; box.classList.remove('hidden'); box.select()
  try{ await navigator.clipboard.writeText(cmd); b.textContent='copied' }catch{ b.textContent='select + copy' }
  setTimeout(()=>{ b.textContent='copy fli decide' },1500)
})

// ── what the readers could not place ──
const warn=[]
if(M.unparsed.length) warn.push(M.unparsed.length+' line(s) have a record\\'s shape and parsed to nothing — first at '+M.unparsed[0].file+':'+M.unparsed[0].line+'. Run fli register:check.')
if(M.duplicates.length) warn.push(M.duplicates.length+' id(s) issued twice — '+M.duplicates.map(d=>d.id).slice(0,5).join(', ')+'. Run fli register:check.')
if(!M.prefix) warn.push('package.json declares no registers prefix, so no issue row or ruling can be read.')
if(warn.length) $('warn').innerHTML='<article class="alert warning"><div class="alert-content"><strong>The registers disagree with themselves</strong><p class="text-sm">'+warn.map(esc).join('<br>')+'</p></div></article>'

route()
`
