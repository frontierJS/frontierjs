/**
 * `fli mesa:pack` — one `.mesa` component compiled `target: 'server'` and
 * bundled into a module that renders a whole page with no Mesa, no
 * `@frontierjs/css` and no document at runtime (`FJS-D1934`). A package that
 * ships a page this way takes no dependency on either: the bytes are
 * committed as a `*.snapshot.js`, and the `snapshots` phase reruns the header
 * with `--check` to keep them equal to the source.
 *
 * The module exports `render(props)`, the full document, and `STYLE_HASH`,
 * the `sha256-…` of the one `<style>` it inlines, for a `style-src` policy.
 *
 * Both packages are resolved from the cli, never from the caller: the package
 * holding the page need not depend on mesa, and the page must be packed by the
 * same mesa the cli was tested against.
 */

import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir }                                           from 'node:os'
import { basename, dirname, join, relative }                from 'node:path'
import { createHash }                                       from 'node:crypto'
import { fileURLToPath }                                    from 'node:url'

const resolveFile = (spec) => fileURLToPath(import.meta.resolve(spec))

// ─── snapshotName ─────────────────────────────────────────────────────────────

/** `Authorize.mesa` → `Authorize.snapshot.js`, beside it. */
export const snapshotName = (source) => basename(source).replace(/\.mesa$/, '') + '.snapshot.js'

// ─── header ───────────────────────────────────────────────────────────────────
//
// The `snapshots` phase reruns this argv from the snapshot's own directory, so
// every path in it is relative to that directory, and each token must pass
// `ARG` in core/snapshots.js or the snapshot is graded as having no generator.

export function header({ source, css, outFile }) {
  const dir  = dirname(outFile)
  const argv = ['fli', 'mesa:pack', relative(dir, source)]
  if (css.length) argv.push('--css', css.join(','))
  if (basename(outFile) !== snapshotName(source) || dir !== dirname(source)) argv.push('--out', relative(dir, outFile))
  return `/* generated by: ${argv.join(' ')} */`
}

// ─── cssLayers ────────────────────────────────────────────────────────────────
//
// A partial's cascade layer is the one `@frontierjs/css`'s own index.css
// imports it into, read from that file so a subset cannot disagree with the
// whole package about which rule wins.

function cssLayers() {
  const index = readFileSync(resolveFile('@frontierjs/css'), 'utf8')
  const order = index.match(/^@layer\s+([^;]+);/m)?.[1].split(',').map(s => s.trim()) ?? []
  const layerOf = new Map()
  for (const m of index.matchAll(/^@import\s+'\.\/([^']+)\.css'\s+layer\((\w+)\)/gm)) layerOf.set(m[1], m[2])
  return { order, layerOf }
}

// ─── cssSubset ────────────────────────────────────────────────────────────────

/**
 * The named partials minified as one stylesheet, in the order given, each in
 * its index.css layer. A partial index.css does not import is refused by
 * name: it has no layer, and unlayered it would outrank every component.
 */
export async function cssSubset(partials, tmp) {
  if (!partials.length) return ''
  const { order, layerOf } = cssLayers()
  const lines = []
  const used  = new Set()
  for (const spec of partials) {
    const name  = spec.replace(/^@frontierjs\/css\//, '').replace(/\.css$/, '')
    const layer = layerOf.get(name)
    if (!layer) throw new Error(`--css names ${spec}, which @frontierjs/css's index.css does not import, so it has no layer`)
    used.add(layer)
    lines.push(`@import '${resolveFile(`@frontierjs/css/${name}.css`)}' layer(${layer});`)
  }
  const entry = join(tmp, 'subset.css')
  writeFileSync(entry, `@layer ${order.filter(l => used.has(l)).join(', ')};\n${lines.join('\n')}\n`)
  return (await build(entry, 'browser')).trim()
}

// ─── compileServer ────────────────────────────────────────────────────────────

/** The component as `target: 'server'` JS importing the runtimes by absolute path, and its own style. */
export async function compileServer(source) {
  const { compile } = await import(import.meta.resolve('@frontierjs/mesa'))
  const ctx = await compile(readFileSync(source, 'utf8'), { target: 'server', filename: basename(source), dev: false })
  const errors = ctx.analysis?.errors ?? []
  if (errors.length) throw new Error(`${basename(source)}: ${errors[0].message ?? errors[0]}`)
  const js = ctx.result
    .replace(/'@frontierjs\/mesa\/runtime\/server'/g, JSON.stringify(resolveFile('@frontierjs/mesa/runtime/server')))
    .replace(/'@frontierjs\/mesa\/runtime'/g, JSON.stringify(resolveFile('@frontierjs/mesa/runtime')))
  return { js, css: (ctx.css?.result ?? ctx.css?.code ?? '').trim() }
}

// ─── pageModule ───────────────────────────────────────────────────────────────

// The entry the bundle is built from. `render` is the only code it adds; the
// render itself is Mesa's `startRender`, which leaves a `<mesa:head>` in
// `out.head` for this document's head rather than refusing it.
const pageModule = (style) => `import Component from './component.js'
import { startRender } from ${JSON.stringify(resolveFile('@frontierjs/mesa/runtime'))}
const STYLE = ${JSON.stringify(style)}
export const STYLE_HASH = ${JSON.stringify(styleHash(style))}
export function render(props) {
  const { out, dispose, waiting } = startRender(Component, props)
  dispose()
  if (waiting) {
    waiting.catch(() => {})
    throw new Error('the page has an {#await} still pending, and a packed page renders synchronously')
  }
  return '<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width, initial-scale=1">' + (out.head ?? []).join('') +
    '<style>' + STYLE + '</style></head><body>' + out.join('').trim() + '</body></html>'
}
`

/** What a `style-src` names for exactly this text. */
export const styleHash = (style) => 'sha256-' + createHash('sha256').update(style, 'utf8').digest('base64')

async function build(entry, target) {
  const result = await Bun.build({ entrypoints: [entry], target, format: 'esm', minify: true })
  if (!result.success) throw new Error(result.logs.map(l => l.message ?? String(l)).join('\n'))
  return result.outputs[0].text()
}

// ─── packMesa ─────────────────────────────────────────────────────────────────

/**
 * The snapshot's whole text for `source`, as `outFile` would hold it. The temp
 * directory's name never reaches the output, which the reproducibility test
 * proves by packing twice.
 */
export async function packMesa({ source, css = [], outFile = join(dirname(source), snapshotName(source)) }) {
  const tmp = mkdtempSync(join(tmpdir(), 'mesa-pack-'))
  try {
    const subset    = await cssSubset(css, tmp)
    const component = await compileServer(source)
    const style     = [subset, component.css].filter(Boolean).join('')
    if (/<\/style/i.test(style)) throw new Error('the stylesheet contains </style, which would end the page\'s <style> early')

    writeFileSync(join(tmp, 'component.js'), component.js)
    writeFileSync(join(tmp, 'entry.js'), pageModule(style))
    const code = await build(join(tmp, 'entry.js'), 'bun')
    return `${header({ source, css, outFile })}\n${code}`
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}
