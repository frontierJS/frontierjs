/**
 * core/desktop-sidecar.js — what `fli make:desktop --sidecar` adds to a desktop
 * surface: the shell starts its OWN API (FJS-D1815).
 *
 * The API is compiled to one bun binary with the @frontierjs packages inside
 * (desktop/sidecar/), the app's own files ship beside it as the bundle's
 * resources, and the shell supervises it: a free 127.0.0.1 port, data in the
 * OS app-data directory, `globalThis.__sierraApiUrl` handed to the page, a
 * restart on the same port, a tray, a single instance. Lifted from immich's
 * hand-built shell (fjs-prototypes/immich PLAN 1b.1–1b.2); the long files are
 * templates under ./desktop-sidecar/, filled with the app's names here.
 *
 * Without --sidecar nothing here is called and make:desktop writes what it
 * always has: example/desktop/ is held byte for byte as that output.
 */

import { existsSync, readFileSync } from 'fs'
import * as fs from 'fs'
import * as path from 'path'
import { dirname, join, resolve } from 'path'
import { fileURLToPath } from 'url'

const TEMPLATES = join(dirname(fileURLToPath(import.meta.url)), 'desktop-sidecar')

/** Where the shell expects the sidecar binary, triple suffix stripped. */
export const sidecarName = (slug) => `${slug}-api`

/**
 * Every `@frontierjs/*` specifier the API's own code imports, sorted — what the
 * sidecar compiles in (portable-install Phase 2.2). Scans api/index.*, api/src
 * and api/config; skips test/, type-only imports and data subpaths (a `.lite`
 * or `.css` is copied, not compiled).
 *
 * Self-contained on purpose: make-sidecar.ts carries this function's source
 * (`Function#toString`), so the build derives the list the same way the
 * scaffold does. Take `fs` and `path` as arguments and close over nothing.
 */
export function frontierSpecifiers(root, fs, path) {
  const api = path.join(root, 'api')
  const files = []
  const walk = (dir) => {
    if (!fs.existsSync(dir)) return
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name)
      if (e.isDirectory()) { if (e.name !== 'test' && e.name !== 'node_modules') walk(p) }
      else if (/\.(m?[jt]s)$/.test(e.name) && !/\.(test|spec)\.[mc]?[jt]s$/.test(e.name) && !e.name.endsWith('.d.ts')) files.push(p)
    }
  }
  for (const f of ['index.ts', 'index.js']) if (fs.existsSync(path.join(api, f))) files.push(path.join(api, f))
  walk(path.join(api, 'src'))
  walk(path.join(api, 'config'))
  const found = new Set()
  const patterns = [
    /(?:^|[\n;])\s*(?:import|export)\s+(type\s+)?[^'";]*?\bfrom\s*['"](@frontierjs\/[^'"]+)['"]/g,
    /(?:^|[\n;])\s*import\s*()['"](@frontierjs\/[^'"]+)['"]/g,
    /\bimport\s*\(\s*()['"](@frontierjs\/[^'"]+)['"]\s*\)/g,
  ]
  for (const f of files) {
    // Line comments only: a block-comment strip would eat a glob like 'src/**/*.ts'.
    const src = fs.readFileSync(f, 'utf8').replace(/^\s*\/\/.*$/gm, '')
    for (const re of patterns) {
      for (const m of src.matchAll(re)) {
        if (m[1]) continue
        if (/\.(lite|css|json|md)$/.test(m[2])) continue
        found.add(m[2])
      }
    }
  }
  return [...found].sort()
}

/** desktop/sidecar/bundled.ts for these specifiers. Self-contained, like the above. */
export function bundledSource(specs) {
  const lines = [
    '// desktop/sidecar/bundled.ts — GENERATED by make-sidecar.ts on every build from',
    "// the API's own imports of @frontierjs/*; an edit here is overwritten.",
    '//',
    '// Every package compiled into the sidecar. The app\'s files stay on disk and',
    '// import these through stubs under app/node_modules that re-export the module',
    '// objects below: one instance of each, since `$` context and the registries',
    '// are module state (IDEAS/portable-install.md, walls 1–2).',
    ...specs.map((s, i) => `import * as m${i} from '${s}'`),
    '',
    'export const bundled: Record<string, object> = {',
    ...specs.map((s, i) => `  '${s}': m${i},`),
    '}',
    '',
    ';(globalThis as Record<string, unknown>).__fjsBundled = bundled',
    '',
  ]
  return lines.join('\n')
}

/** The app's API prefix as junction.config.js states it, `/api` when it does not. */
export function apiPrefixOf(root) {
  const file = resolve(root, 'api', 'config', 'junction.config.js')
  if (!existsSync(file)) return '/api'
  const m = readFileSync(file, 'utf8').match(/apiPrefix\s*:\s*['"]([^'"]*)['"]/)
  return m ? m[1] : '/api'
}

function fill(template, { slug, productName, apiPrefix = '/api' }) {
  return readFileSync(join(TEMPLATES, template), 'utf8')
    .replaceAll('__SLUG__', slug)
    .replaceAll('__PRODUCT__', productName)
    .replaceAll('__API_PREFIX__', apiPrefix)
}

// ─── the sidecar's own files ─────────────────────────────────────────────────

export function sidecarLauncher(names) { return fill('launcher.ts', names) }

export function sidecarMake(names) {
  return fill('make-sidecar.ts', names)
    // A function replacer: the sources hold `$` sequences a string replacement reads.
    .replace('/*__SPECIFIERS_FN__*/', () =>
      `const frontierSpecifiers: (root: string, fs: any, path: any) => string[] = ${frontierSpecifiers.toString()}`)
    .replace('/*__BUNDLED_FN__*/', () =>
      `const bundledSource: (specs: string[]) => string = ${bundledSource.toString()}`)
}

/** bundled.ts as the scaffold first writes it; make-sidecar.ts rewrites it per build. */
export function sidecarBundled(root) {
  return bundledSource(frontierSpecifiers(root, fs, path))
}

