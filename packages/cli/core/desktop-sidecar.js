/**
 * deploy/build.mjs, sidecar shape: the default script with the sidecar's
 * refusal and its staging step. Edits are exact replacements so the default
 * shape stays the one source; a replacement that stops matching throws here,
 * in the generator's tests, rather than writing a script that forgot a step.
 */
export function sidecarBuildScript(base) {
  const edits = [
    [/(\/\/   bun run build:desktop -- --release\n)/,
      '$1//   bun run build:desktop -- --release --target bun-windows-x64   the sidecar\'s bun target\n' +
      '//   bun run build:desktop -- --target bun-windows-x64 --no-shell  stage screens and sidecar only,\n' +
      '//                                     for a shell compiled on the target OS (tauri-build copies them)\n'],
    [/(const release = process\.argv\.includes\('--release'\)\n)/,
      "$1const ti      = process.argv.indexOf('--target')\nconst target  = ti > 0 ? process.argv[ti + 1] : 'bun-linux-x64'\n"],
    // biome-ignore lint/suspicious/noTemplateCurlyInString: the placeholders belong to the template literal in the script this writes, not to this string
    [/(\nrun\('cargo', )/, "\nif (process.argv.includes('--no-shell')) {\n  console.log(`\\n  staged for a shell built elsewhere: ${dist} and ${join(SHELL, 'sidecar')}`)\n  process.exit(0)\n}\n$1"],
    [/if \(config\.api === undefined\) refuse\(/, 'if (config.api === undefined && !config.sidecar) refuse('],
    [/env: \{ \.\.\.process\.env, \.\.\.\(config\.api \? /, 'env: { ...process.env, ...(config.api && !config.sidecar ? '],
    [/\nif \(config\.api && !bundleNames\(dist, config\.api\)\) refuse\(/,
      `
// With a sidecar the shell starts its own API on a port picked at launch
// (FJS-D1815), so no build can inline it and none is: the page reads
// globalThis.__sierraApiUrl, which the shell sets. A bundle that does not read
// it is an app pointed at tauri://localhost — the same failure the api refusal
// below guards. The sidecar is staged before the shell compiles, which copies it.
if (config.sidecar) {
  if (!bundleNames(dist, '__sierraApiUrl')) refuse(
    \`the build finished and no file under \${dist} reads __sierraApiUrl. The shell starts its own \` +
    'API on a port picked at launch and hands the page that origin through it; a sierra older than ' +
    'FJS-D1815, or a sierra.config.js with no junction.url, sends every call to tauri://localhost.')
  run('bun', [join(DESKTOP, 'sidecar', 'make-sidecar.ts'), '--target', target], { cwd: APP })
} else if (config.api && !bundleNames(dist, config.api)) refuse(`],
  ]
  let out = base
  for (const [re, to] of edits) {
    if (!re.test(out)) throw new Error(`sidecarBuildScript: the default build.mjs no longer matches ${re}`)
    out = out.replace(re, to)
  }
  return out
}

/** desktop.config.js, sidecar shape: the default with `sidecar: true` and why. */
export function sidecarConfig(base) {
  const re = /\nexport default \{\n/
  if (!re.test(base)) throw new Error('sidecarConfig: the default desktop.config.js no longer matches')
  return base.replace(re, `//
// \`sidecar: true\` is the installed app running its OWN API (FJS-D1815): the
// shell starts desktop/sidecar's compiled binary on a free 127.0.0.1 port and
// hands the page that origin at run time, so \`api\` is then only what
// \`fli desktop:run\` and a dev URL use, and the bundle inlines none.

export default {
  sidecar: true,
`)
}
