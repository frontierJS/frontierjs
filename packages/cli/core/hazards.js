// ─── hazards.js — which live hazard a `fli check` rule grades ────────────────
//
// The three realm skills (`.claude/skills/{data,api,ui}-hazards/SKILL.md`) hold
// one bullet per hazard, and `FJS-D133` makes `fli check`'s rule table where the
// catalog executes. Nothing said which bullets a rule had reached, so a hazard
// that lives only in prose read exactly like one a rule grades — and a hazard
// in prose is one every new session re-learns by failing.
//
// The answer has `invariants.snapshot.md`'s shape (`FJS-D190`): a rule declares
// the hazard it serves, the table is read off the rules, and a hazard nothing
// declares is a `none` row. There is no declared reason for a `none`: the gap
// is the finding, and it is published rather than explained.
//
// ── A hazard has no number, so a rule names it by its lead ───────────────────
//
// `hazard: 'data: A soft-deleted row keeps'` — the realm, then a prefix of the
// bullet's bold lead. The prefix must match exactly ONE bullet; `hazard-enforcer`
// reds zero or two, so rewording a bullet out from under its rule is a red
// rather than a row that quietly turned `none`.

import { readFileSync, readdirSync } from 'node:fs'
import { join }                      from 'node:path'

export const REALMS = ['data', 'api', 'ui']

const read = p => { try { return readFileSync(p, 'utf8') } catch { return null } }

// ─── the hazards themselves ──────────────────────────────────────────────────
//
// Parsed from each skill's index rather than restated: a bullet whose line
// opens with a bold lead, nested ones included, under the `## ` section it
// sits in. The lead is the hazard's rule; the reference file holds the rest.
//
// `names` is what a session would write when it meets the hazard: the defect
// ids and the error classes the entry cites, from the index line and the
// reference bullet with the same lead. A ruling id is not a name — a session
// drafting an owed ruling cites `FJS-D###` as its argument without meeting the
// hazard — and neither is the lead's prose, whose code spans (`const`, `9`,
// `asSystem()`) turn up in most sessions whatever they were doing.

export function readHazards(root) {
  const out = []
  for (const realm of REALMS) {
    const dir  = join(root, '.claude', 'skills', `${realm}-hazards`)
    const text = read(join(dir, 'SKILL.md'))
    if (text === null) continue
    const detail = referenceLines(join(dir, 'references'))
    let section = null
    for (const line of text.split('\n')) {
      const h = /^## (.+)$/.exec(line)
      if (h) { section = h[1].trim(); continue }
      const b = /^(\s*)- \*\*(.+?)\*\*/.exec(line)
      if (!b || !section) continue
      const lead = b[2].trim()
      out.push({ realm, section, lead, nested: b[1].length > 0, names: namesIn(`${line}\n${detail.get(lead) ?? ''}`) })
    }
  }
  return out
}

function referenceLines(dir) {
  const byLead = new Map()
  let files = []
  try { files = readdirSync(dir).filter(f => f.endsWith('.md')) } catch {}
  for (const f of files) for (const line of (read(join(dir, f)) ?? '').split('\n')) {
    const b = /^\s*- \*\*(.+?)\*\*/.exec(line)
    if (b) byLead.set(b[1].trim(), line)
  }
  return byLead
}

function namesIn(text) {
  return [...new Set([...text.matchAll(/\bFJS-\d+\b|\b[A-Z][A-Za-z]*Error\b/g)].map(m => m[0]))]
}

// ─── resolving a rule's `hazard:` ────────────────────────────────────────────

export function parseHazardKey(key) {
  const m = /^(\w+):\s*(.+)$/.exec(key ?? '')
  return m ? { realm: m[1], prefix: m[2] } : null
}

export function matchHazard(hazards, key) {
  const k = parseHazardKey(key)
  if (!k) return []
  return hazards.filter(h => h.realm === k.realm && h.lead.startsWith(k.prefix))
}

// ─── the whole table ─────────────────────────────────────────────────────────
//
//   hazardCoverage({ root, rules })
//     → { hazards: [{ realm, section, lead, nested, rules }], unresolved: [{ rule, key, matches }] }
//
// A rule whose key matches zero or several bullets lands in `unresolved` and
// grades nothing, so the table never credits a hazard on a guess.

export function hazardCoverage({ root, rules = [] } = {}) {
  const hazards = readHazards(root).map(h => ({ ...h, rules: [] }))
  const unresolved = []
  for (const rule of rules) {
    if (!rule.hazard) continue
    const matches = matchHazard(hazards, rule.hazard)
    if (matches.length === 1) matches[0].rules.push({ id: rule.id, title: rule.title })
    else unresolved.push({ rule: rule.id, key: rule.hazard, matches: matches.length })
  }
  return { hazards, unresolved }
}

// ─── rendering ───────────────────────────────────────────────────────────────

const cell = s => s.replace(/\|/g, '\\|')

export function renderHazards({ hazards }) {
  const out = []
  const graded = hazards.filter(h => h.rules.length).length

  out.push('<!-- generated by: fli ws:hazards -->')
  out.push('')
  out.push('# Hazards — which `fli check` rule grades each one')
  out.push('')
  out.push('Generated. The realm skills\' indexes (`.claude/skills/{data,api,ui}-hazards/SKILL.md`)')
  out.push('are the source of the list; a `fli check` rule declares the hazard it grades with')
  out.push('`hazard: \'<realm>: <prefix of the bold lead>\'` and is read off that table, and')
  out.push('`fli check`\'s `hazard-enforcer` reds a key matching no bullet or two.')
  out.push('')
  out.push('**`none` is an answer.** A hazard no rule grades reads exactly like one that is')
  out.push('graded, and lives only in prose — so every new session re-learns it by failing.')
  out.push('')
  out.push(`Graded: **${graded} of ${hazards.length}**.`)
  out.push('')

  for (const realm of REALMS) {
    const mine = hazards.filter(h => h.realm === realm)
    if (!mine.length) continue
    const n = mine.filter(h => h.rules.length).length
    out.push(`## ${realm} — ${n} of ${mine.length}`)
    out.push('')
    for (const section of [...new Set(mine.map(h => h.section))]) {
      out.push(`### ${section}`)
      out.push('')
      out.push('| Hazard | Graded by |')
      out.push('| --- | --- |')
      for (const h of mine.filter(x => x.section === section)) {
        const lead = `${h.nested ? '↳ ' : ''}${cell(h.lead)}`
        const by = h.rules.length ? h.rules.map(r => `\`${r.id}\``).join(', ') : '**none**'
        out.push(`| ${lead} | ${by} |`)
      }
      out.push('')
    }
  }

  return out.join('\n') + '\n'
}
