// desktop/shell/src/main.rs — the native window around the bundled screens.
//
// The page is served from tauri://localhost (http://tauri.localhost on Windows
// and Android), so the API is always another origin and its CORS list has to
// name this origin (FJS-1090).
//
// The shell runs its OWN API (FJS-D1815): the sidecar `__SLUG__-api`, a bun
// binary with the packages compiled in (desktop/sidecar/), beside this one as
// a bundle.externalBin, with the app's files as bundle.resources under app/.
// It is started on a free 127.0.0.1 port picked here at launch, its data in
// the OS app-data directory (api/, api-debug/ in a debug build), and the window is built only once its
// __API_PREFIX__/health answers. A port no build can know reaches the page as
// `globalThis.__sierraApiUrl`, set by an initialization script before any page
// script runs; sierra reads it ahead of the inlined FRONTIER_PUBLIC_API_URL.
// The sidecar is stopped on exit by closing its stdin, which is also what
// stops it when this process dies some other way, SIGKILL included. One that
// dies on its own is restarted on the SAME port, so the origin the page was
// handed stays right, with a backoff; five deaths inside a minute and the shell
// stops trying and says so in a dialog.
//
// Closing the window hides it: the API keeps working. The tray's Open brings
// it back, Start at login is an opt-in login item (off until ticked), and Quit
// is the one way out. A second launch focuses this one instead of starting a
// second API on the same app.db (single-instance plugin).
//
// `withGlobalTauri` puts the dialog plugin's API on window.__TAURI__, so a
// screen can offer a native folder picker inside the shell only
// (`window.__TAURI__?.dialog.open({ directory: true })`; a browser has none).
// capabilities/default.json grants the page dialog open and nothing else: no
// fs, because the API reads the drives, not the page.
//
// frontendDist is compiled INTO the binary. Rebuilding the screens without
// rebuilding this crate runs the previous bundle.
//
// A debug build injects a probe when FJS_DESKTOP_PROBE names a script.
// WebKitGTK and WKWebView speak no CDP, so a drive cannot reach into the page
// the way a browser drive does; the probe runs inside it and reports through
// the two commands below.
//
// A debug build loads FRONTIER_DESKTOP_URL instead of the bundle when it is set —
// fli dev:desktop points it at the screens' dev server. That page's origin is
// the server's, not tauri://localhost, so an origin or CORS fault shows only
// in the bundled build.
//
// A release build reads neither variable and registers no command, so a
// shipped app cannot be scripted or repointed from its environment. The same
// holds for FJS_DESKTOP_BREAK_RESTART, the debug build's way to prove the
// give-up path: every restart is started on an app directory that is not there.
//
// Generated by `fli make:desktop --sidecar`; the sidecar's own files are
// desktop/sidecar/.
//
// A webview with no new-window handler drops every target=_blank link without
// a sound, so each one goes to the system browser instead.


// A release build on Windows is a windowed program, or it opens a console of
// its own beside the window. Debug keeps the console for the probe's output.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

use std::collections::VecDeque;
use std::io::{Read, Write};
use std::net::{Ipv4Addr, TcpListener, TcpStream};
use std::path::PathBuf;
use std::process::{Child, Command, ExitStatus, Stdio};
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Mutex;
use std::time::{Duration, Instant};

use tauri::menu::{CheckMenuItem, Menu, MenuItem};
use tauri::tray::TrayIconBuilder;
use tauri::webview::NewWindowResponse;
use tauri::{AppHandle, Manager, RunEvent, WebviewUrl, WebviewWindowBuilder, WindowEvent};
use tauri_plugin_autostart::{MacosLauncher, ManagerExt};
use tauri_plugin_dialog::{DialogExt, MessageDialogKind};

const SIDECAR: &str = "__SLUG__-api";
const HEALTH_WAIT: Duration = Duration::from_secs(30);
const MAX_DEATHS: usize = 5;
const DEATH_WINDOW: Duration = Duration::from_secs(60);

#[derive(Default)]
struct Sidecar {
    child: Mutex<Option<Child>>,
    quitting: AtomicBool,
}

#[cfg(debug_assertions)]
#[tauri::command]
fn probe_report(line: String) {
    println!("[probe] {line}");
}

#[cfg(debug_assertions)]
#[tauri::command]
fn probe_done(app: tauri::AppHandle, code: i32) {
    quit(&app, code);
}

// What the window's close button does, sent from inside the page.
#[cfg(debug_assertions)]
#[tauri::command]
fn probe_close(window: tauri::WebviewWindow) {
    let _ = window.close();
}

fn probe_script() -> Option<String> {
    if !cfg!(debug_assertions) {
        return None;
    }
    let path = std::env::var("FJS_DESKTOP_PROBE").ok()?;
    match std::fs::read_to_string(&path) {
        Ok(script) => Some(script),
        Err(e) => panic!("FJS_DESKTOP_PROBE={path} could not be read: {e}"),
    }
}

fn dev_url() -> Option<tauri::Url> {
    if !cfg!(debug_assertions) {
        return None;
    }
    let raw = std::env::var("FRONTIER_DESKTOP_URL").ok()?;
    match raw.parse() {
        Ok(url) => Some(url),
        Err(e) => panic!("FRONTIER_DESKTOP_URL={raw} is not a URL: {e}"),
    }
}

fn break_restarts() -> bool {
    cfg!(debug_assertions) && std::env::var("FJS_DESKTOP_BREAK_RESTART").as_deref() == Ok("1")
}

// Only http(s): anything else would hand the OS opener a file or a scheme
// handler the page chose.
fn open_in_browser(url: &tauri::Url) {
    if !matches!(url.scheme(), "http" | "https") {
        return;
    }
    let (cmd, args): (&str, &[&str]) = if cfg!(target_os = "macos") {
        ("open", &[])
    } else if cfg!(windows) {
        ("rundll32", &["url.dll,FileProtocolHandler"])
    } else {
        ("xdg-open", &[])
    };
    match std::process::Command::new(cmd).args(args).arg(url.as_str()).spawn() {
        // Reaped on its own thread, or every click leaves a zombie behind.
        Ok(mut child) => {
            std::thread::spawn(move || child.wait());
        }
        Err(e) => eprintln!("{cmd} could not open {url}: {e}"),
    }
}

// ─── the sidecar ──────────────────────────────────────────────────────────

// Bound and released: the sidecar binds it a moment later. Another process
// could take it in between; the health wait then fails by name.
fn free_port() -> std::io::Result<u16> {
    Ok(TcpListener::bind((Ipv4Addr::LOCALHOST, 0))?.local_addr()?.port())
}

// Tauri copies an externalBin beside the shell with its triple suffix removed,
// in a cargo build and in every bundle, which is all the shell plugin's
// sidecar API resolves too.
fn sidecar_path() -> Result<PathBuf, String> {
    let exe = std::env::current_exe().map_err(|e| format!("cannot find this executable: {e}"))?;
    let dir = exe.parent().ok_or("this executable has no directory")?;
    Ok(dir.join(format!("{SIDECAR}{}", std::env::consts::EXE_SUFFIX)))
}

// The app-data directory is the identifier's and the webview keeps its own
// storage there, so the API's files go one level down, and a debug build gets
// a directory of its own: its seed must never be a release build's data.
fn api_data_dir(app: &AppHandle) -> Result<PathBuf, String> {
    let base = app.path().app_data_dir().map_err(|e| format!("no app-data directory: {e}"))?;
    Ok(base.join(if cfg!(debug_assertions) { "api-debug" } else { "api" }))
}

fn spawn_api(app: &AppHandle, port: u16, restart: bool) -> Result<Child, String> {
    let data = api_data_dir(app)?;
    std::fs::create_dir_all(&data).map_err(|e| format!("cannot create {}: {e}", data.display()))?;
    let mut files = app.path().resource_dir().map_err(|e| format!("no resource directory: {e}"))?.join("app");
    if restart && break_restarts() {
        files = files.join("FJS_DESKTOP_BREAK_RESTART");
    }
    let bin = sidecar_path()?;
    let at = |name: &str| data.join(name).to_string_lossy().into_owned();
    let mut cmd = Command::new(&bin);
    // The sidecar is a console program; started from a windowed shell without
    // this, Windows opens a console window beside the app for it.
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        cmd.creation_flags(CREATE_NO_WINDOW);
    }
    cmd.current_dir(data.as_path())
        .env("FJS_SIDECAR_APP", &files)
        .env("FJS_SIDECAR_LIFELINE", "1")
        .env("DATABASE_URL", at("app.db"))
        .env("AUDIT_PATH", at("audit.db"))
        .env("STORAGE_ROOT", at("storage"))
        .env("ENCRYPTION_KEY_FILE", at("encryption.key"))
        .env_remove("ENCRYPTION_KEY")
        .env("FRONTIER_PORT_BE", port.to_string())
        .env("FRONTIER_API_URL", format!("http://127.0.0.1:{port}"))
        .env("NODE_ENV", "production")
        .env("FRONTIER_CORS_ORIGINS", "tauri://localhost,http://tauri.localhost")
        .stdin(Stdio::piped())
        .spawn()
        .map_err(|e| format!("{} could not be started: {e}", bin.display()))
}

fn start_api(app: &AppHandle) -> Result<(Child, u16), String> {
    let port = free_port().map_err(|e| format!("no free port on 127.0.0.1: {e}"))?;
    let mut child = spawn_api(app, port, false)?;
    if let Err(e) = wait_healthy(&mut child, port) {
        stop(child);
        return Err(e);
    }
    Ok((child, port))
}

fn wait_healthy(child: &mut Child, port: u16) -> Result<(), String> {
    let deadline = Instant::now() + HEALTH_WAIT;
    loop {
        if let Ok(Some(status)) = child.try_wait() {
            return Err(format!("{SIDECAR} exited ({status}) before __API_PREFIX__/health answered"));
        }
        if health_ok(port) {
            return Ok(());
        }
        if Instant::now() > deadline {
            return Err(format!("{SIDECAR} did not answer __API_PREFIX__/health on 127.0.0.1:{port} within {}s", HEALTH_WAIT.as_secs()));
        }
        std::thread::sleep(Duration::from_millis(100));
    }
}

fn health_ok(port: u16) -> bool {
    let addr = (Ipv4Addr::LOCALHOST, port).into();
    let Ok(mut s) = TcpStream::connect_timeout(&addr, Duration::from_millis(500)) else { return false };
    let _ = s.set_read_timeout(Some(Duration::from_secs(2)));
    if s.write_all(b"GET __API_PREFIX__/health HTTP/1.0\r\nHost: 127.0.0.1\r\n\r\n").is_err() {
        return false;
    }
    let mut head = [0u8; 16];
    let n = s.read(&mut head).unwrap_or(0);
    let line = String::from_utf8_lossy(&head[..n]);
    line.starts_with("HTTP/1.1 200") || line.starts_with("HTTP/1.0 200")
}

// Closing stdin is the sidecar's signal to exit (FJS_SIDECAR_LIFELINE), which
// lets SQLite close its files; a sidecar that has not gone in 5s is killed.
fn stop(mut child: Child) {
    drop(child.stdin.take());
    let deadline = Instant::now() + Duration::from_secs(5);
    while Instant::now() < deadline {
        if let Ok(Some(_)) = child.try_wait() {
            return;
        }
        std::thread::sleep(Duration::from_millis(50));
    }
    let _ = child.kill();
    let _ = child.wait();
}

// Watches the sidecar for an exit nobody asked for and starts it again on the
// same port: the page was handed that origin once, at window build. The
// backoff doubles from 0.5s to 8s; MAX_DEATHS inside DEATH_WINDOW is a sidecar
// that will not stay up, and restarting it forever only hides that.
fn supervise(app: AppHandle, port: u16) {
    std::thread::spawn(move || {
        let mut deaths: VecDeque<Instant> = VecDeque::new();
        loop {
            std::thread::sleep(Duration::from_millis(250));
            let state = app.state::<Sidecar>();
            if state.quitting.load(Ordering::SeqCst) {
                return;
            }
            let exited: Option<ExitStatus> = {
                let mut held = state.child.lock().unwrap();
                match held.as_mut().map(|c| c.try_wait()) {
                    None => return,
                    Some(Ok(Some(status))) => {
                        held.take();
                        Some(status)
                    }
                    Some(_) => None,
                }
            };
            let Some(status) = exited else { continue };
            let now = Instant::now();
            deaths.push_back(now);
            while deaths.front().is_some_and(|t| now.duration_since(*t) > DEATH_WINDOW) {
                deaths.pop_front();
            }
            eprintln!("__SLUG__: {SIDECAR} exited on its own ({status}); {} in the last {}s", deaths.len(), DEATH_WINDOW.as_secs());
            if deaths.len() >= MAX_DEATHS {
                give_up(&app, &format!(
                    "The __PRODUCT__ API ({SIDECAR}) stopped {} times in {} seconds and is not being restarted. \
                     Its last exit was {status}. Quit __PRODUCT__ from the tray and start it again.",
                    deaths.len(), DEATH_WINDOW.as_secs()));
                return;
            }
            let backoff = Duration::from_millis(500 * (1u64 << (deaths.len() - 1).min(4)));
            std::thread::sleep(backoff);
            if state.quitting.load(Ordering::SeqCst) {
                return;
            }
            match spawn_api(&app, port, true) {
                Ok(mut child) => {
                    let pid = child.id();
                    match wait_healthy(&mut child, port) {
                        Ok(()) => eprintln!("__SLUG__: {SIDECAR} restarted on http://127.0.0.1:{port} (pid {pid})"),
                        Err(e) => eprintln!("__SLUG__: the restarted {SIDECAR} is not answering — {e}"),
                    }
                    // Held either way: one that exited is the next death above.
                    *state.child.lock().unwrap() = Some(child);
                }
                Err(e) => {
                    give_up(&app, &format!("The __PRODUCT__ API could not be restarted: {e}"));
                    return;
                }
            }
        }
    });
}

fn give_up(app: &AppHandle, message: &str) {
    eprintln!("__SLUG__: {message}");
    app.dialog().message(message).kind(MessageDialogKind::Error).title("__PRODUCT__").blocking_show();
}

// ─── the window and the tray ──────────────────────────────────────────────

fn show_main(app: &AppHandle) {
    if let Some(w) = app.get_webview_window("main") {
        let _ = w.show();
        let _ = w.unminimize();
        let _ = w.set_focus();
    }
}

// The one way out: the Exit handler below stops the sidecar.
fn quit(app: &AppHandle, code: i32) {
    app.state::<Sidecar>().quitting.store(true, Ordering::SeqCst);
    app.exit(code);
}

fn build_tray(app: &tauri::App) -> tauri::Result<()> {
    let at_login = app.autolaunch().is_enabled().unwrap_or(false);
    let open = MenuItem::with_id(app, "open", "Open", true, None::<&str>)?;
    let login = CheckMenuItem::with_id(app, "autostart", "Start at login", true, at_login, None::<&str>)?;
    let quit_item = MenuItem::with_id(app, "quit", "Quit", true, None::<&str>)?;
    let menu = Menu::with_items(app, &[&open, &login, &quit_item])?;
    let mut tray = TrayIconBuilder::with_id("main").tooltip("__PRODUCT__").menu(&menu);
    if let Some(icon) = app.default_window_icon() {
        tray = tray.icon(icon.clone());
    }
    tray.on_menu_event(move |app, event| match event.id().as_ref() {
        "open" => show_main(app),
        "quit" => quit(app, 0),
        "autostart" => {
            // The item has already toggled itself; the login item follows it,
            // and a refusal puts the tick back to what is true.
            let want = login.is_checked().unwrap_or(false);
            let al = app.autolaunch();
            let done = if want { al.enable() } else { al.disable() };
            if let Err(e) = done {
                eprintln!("__SLUG__: Start at login could not be {}: {e}", if want { "turned on" } else { "turned off" });
            }
            let _ = login.set_checked(al.is_enabled().unwrap_or(false));
        }
        _ => {}
    })
    .build(app)?;
    Ok(())
}

fn main() {
    // The tray's title on Linux is GLib's application name, which defaults to
    // the binary's — `<slug>-desktop` — rather than the product (FJS-3966).
    #[cfg(target_os = "linux")]
    glib::set_application_name("__PRODUCT__");

    let probe = probe_script();
    let dev = dev_url();
    // fli dev:desktop starts the API itself and serves the screens with that
    // origin inlined, so a dev URL runs no sidecar.
    let own_api = dev.is_none();
    let page = match dev {
        Some(url) => WebviewUrl::External(url),
        None => WebviewUrl::App("index.html".into()),
    };

    // Single-instance first, so a second launch exits before it starts anything.
    let builder = tauri::Builder::default()
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| show_main(app)))
        .plugin(tauri_plugin_autostart::init(MacosLauncher::LaunchAgent, None))
        .plugin(tauri_plugin_dialog::init())
        .manage(Sidecar::default())
        .on_window_event(|window, event| {
            if let WindowEvent::CloseRequested { api, .. } = event {
                api.prevent_close();
                let _ = window.hide();
            }
        });
    #[cfg(debug_assertions)]
    let builder = if probe.is_some() {
        builder.invoke_handler(tauri::generate_handler![probe_report, probe_done, probe_close])
    } else {
        builder
    };

    let app = builder
        .setup(move |app| {
            let mut init = String::new();
            // The webview is the page's host whether or not the sidecar runs, so
            // this is declared ahead of the API branch. Mesa's keys() and hotkey()
            // read it to stop refusing <Mod-w> and <C-Tab>: a webview has no tabs
            // to close, and on Linux (WebKitGTK) they reach the page. macOS
            // declares nothing because Tauri's default menu takes Cmd+W first, and
            // Windows nothing because WebView2 is unproven; each adds its own
            // cfg arm once a drive there shows the chords arrive (FJS-4248).
            #[cfg(target_os = "linux")]
            init.push_str("globalThis.__frontierShell = { browserChords: true };\n");
            if own_api {
                match start_api(app.handle()) {
                    Ok((child, port)) => {
                        eprintln!("__SLUG__: API sidecar on http://127.0.0.1:{port} (pid {})", child.id());
                        *app.state::<Sidecar>().child.lock().unwrap() = Some(child);
                        init.push_str(&format!("globalThis.__sierraApiUrl = 'http://127.0.0.1:{port}';\n"));
                        supervise(app.handle().clone(), port);
                    }
                    Err(e) => {
                        eprintln!("__SLUG__: the API could not start — {e}");
                        app.dialog()
                            .message(format!("The __PRODUCT__ API could not start: {e}"))
                            .kind(MessageDialogKind::Error)
                            .title("__PRODUCT__")
                            .blocking_show();
                        std::process::exit(1);
                    }
                }
            }
            if let Some(script) = &probe {
                init.push_str(script);
            }
            let mut window = WebviewWindowBuilder::new(app, "main", page)
                .title("__PRODUCT__")
                .inner_size(1280.0, 900.0)
                .on_new_window(|url, _| {
                    open_in_browser(&url);
                    NewWindowResponse::Deny
                });
            if !init.is_empty() {
                window = window.initialization_script(&init);
            }
            window.build()?;
            build_tray(app)?;
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("the desktop shell failed to start");

    app.run(|handle, event| {
        if let RunEvent::Exit = event {
            let state = handle.state::<Sidecar>();
            state.quitting.store(true, Ordering::SeqCst);
            let held = state.child.lock().unwrap().take();
            if let Some(child) = held {
                stop(child);
            }
        }
    });
}
