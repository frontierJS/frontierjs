// status against it is the whole audit: blessed-and-unused is dead doctrine,
// used-and-unnamed is vocabulary nobody defined, and a forbidden word in live
// prose is the drift § 2 exists to prevent.

// The § 2 section, cut out at the same boundaries `architectVocabulary` reads
// it by — the heading and the next `## `.
function withoutSectionTwo(text) {
  const parts = text.split(/^## 2\. /m)
  if (parts.length < 2) return text
  const rest = parts[1].split(/^## /m)
  return `${parts[0]}${rest.slice(1).map(s => `## ${s}`).join('')}`
}

export function architectVocabulary(root) {
  const file = join(root, 'ARCHITECT.md')
  const out  = { blessed: [], forbidden: [], clarified: [], notYetNamed: [], found: false }
  if (!existsSync(file)) return out

  const text    = readFileSync(file, 'utf8')
  const section = text.split(/^## 2\. /m)[1]
  if (!section) return out
  out.found = true

  const body       = section.split(/^## /m)[0]
  const notNamedAt = body.indexOf('### Not yet named')
  const head       = notNamedAt < 0 ? body : body.slice(0, notNamedAt)
  const tail       = notNamedAt < 0 ? ''   : body.slice(notNamedAt)

  for (const line of head.split('\n')) {
    const row = line.match(/^\|\s*\*\*([^*]+)\*\*\s*\|([^|]*)\|/)
    if (row) {
      out.blessed.push(row[1].trim())
      for (const alt of row[2].split(',')) {
        const word = alt.trim().replace(/\s*\(.*$/, '')
        if (word && !/^\s*$/.test(word)) out.forbidden.push(word)
      }
      continue
    }
    const bullet = line.match(/^-\s+\*\*([^*]+)\*\*/)
    if (bullet) out.clarified.push(bullet[1].replace(/[`.,]/g, '').trim())
  }

  for (const line of tail.split('\n')) {
    const bullet = line.match(/^-\s+\*\*([^*]+)\*\*/)
    if (bullet) out.notYetNamed.push(bullet[1].replace(/[`.,]/g, '').trim())
  }

  return out
}

// ─── VOCABULARY.md, the authored half ─────────────────────────────────────────
//
// The words somebody has DEFINED, which no scan can produce. Read here and
// joined to the measurements, so a term is defined in one place and counted in
// another. A word that is not a term of this framework is not labelled there —
// it is excluded above, where the classifier can act on it.

export function authoredVocabulary(root) {
  const file = join(root, 'VOCABULARY.md')
  const out  = new Map()
  if (!existsSync(file)) return out

  // Columns are found by the header row's names, so a column added to the
  // file does not shift `means` into `note` for every row below it.
  let cols = null
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (!/^\|.*\|\s*$/.test(line)) { cols = null; continue }
    const cells = line.trim().slice(1, -1).split('|').map(c => c.trim())
    if (cells[0] === 'Term') { cols = Object.fromEntries(cells.map((c, i) => [c.toLowerCase(), i])); continue }
    if (!cols) continue
    const at     = (name) => cols[name] == null ? '' : (cells[cols[name]] ?? '')
    const term   = at('term')
    const status = at('status').replace(/`/g, '')
    // A row is a TERM only when its status is one of the four, which is the
    // same test the file asks a reader to apply.
    if (!['blessed', 'refused', 'alias', 'open'].includes(status)) continue
    out.set(term.toLowerCase(), { term, status, home: at('home'), under: at('under'), means: at('means'), note: at('note') })
  }
  return out
}

// ─── a package's own vocabulary ─────────────────────────────────────────────────
//
// `VOCABULARY.md` is the root vocabulary and it is not the only one. A package
// that defines its own terms well enough to CHECK them has named them, and
// reporting those terms as named nowhere is the measurement being wrong about
// the tree — @frontierjs/css defines 56 and every one of them read `unnamed`.
//
// The vocabulary is READ, never copied here. A copy is 56 rows maintained by hand
// and stale the first time css renames one, which is what the root file already
// says about itself: defined in one place, measured in another.
//
// **Named rather than discovered.** A `*/vocabulary.json` glob would adopt any
// file with that name; declaring a term is a claim somebody makes, which is the
// same reason `phrases` is scanned from the two authored halves instead of
// found. One row here is what the next package costs.
const PACKAGE_REGISTERS = [
  { owner: 'css', file: 'packages/css/vocabulary.json', read: readCssVocabulary },
]

// The generated half of `packages/css/vocabulary.js`, which is a classic script
// by necessity and says so in its own header. `build-vocabulary.js` writes the
// JSON and `test/specs/vocabulary.spec.js` grades both against the real CSSOM,
// so what is read here is already held to the stylesheet.
//
// Two shapes, because css names two kinds of word. `terms` is the vocabulary —
// one element and one meaning each. `notATerm`'s KEYS are the axes it declares
// a word can be instead of a term, and those names are vocabulary themselves:
// Invariant 13 is written in them (*a tone, and a treatment*), and `Treatment`
// was the most-used unnamed concept in the package before this read it.
function readCssVocabulary(text) {
  const out = new Map()
  const doc = JSON.parse(text)
  // A tier is css's answer to *what is this inside*, which is the root file's
  // `Under` column; reading it here is what keeps the UI rows' container half
  // from being authored twice and drifting the first time css re-tiers a term.
  for (const t of doc.terms ?? []) {
    if (!t?.term) continue
    out.set(t.term.toLowerCase(), {
      term:  t.term,
      means: t.meaning ?? '',
      note:  t.element ?? '',
      home:  'UI',
      under: t.tier ? `${t.tier} tier` : '',
    })
  }
  // After the terms, so `Heading` keeps the definition rather than the axis —
  // it is both a term and the name of the group css files its own h1–h6 under.
  for (const axis of Object.keys(doc.notATerm ?? {})) {
    const term = axis.replace(/^./, c => c.toUpperCase())
    if (out.has(term.toLowerCase())) continue
    out.set(term.toLowerCase(), {
      term,
      means: `An axis a class can be on instead of being a term — ${(doc.notATerm[axis] ?? []).length} of them`,
      note:  'axis',
    })
  }
  return out
}

// The root row wins, and a package's `Under` fills only a UI row that left
// its own blank. Home is the test for *same sense*: `Table` is a Data row and
// css's `<table>` is not its parent's child, `Surface` is a Framework row and
// css's Base shape is a different word spelled the same, and an authored
// `Under` (Switch under Select task) is a placement css cannot see.
export function placed(root, pkg) {
  if (!root) return pkg ?? null
  if (!pkg || root.under || root.home !== pkg.home || !pkg.under) return root
  return { ...root, under: pkg.under, underFrom: pkg.owner }
}

// Every package vocabulary, joined. A malformed or missing one is SKIPPED rather
// than thrown: this command is exploratory and ungated on purpose (`FJS-1211`),
// so it has to keep running while a vocabulary is being written. What is not
// allowed is skipping quietly — the count each one contributed is carried out
// to the presentation, because a vocabulary that stopped resolving returns every
// one of its terms to `unnamed`, which reads exactly like a package that never
// named anything.
export function packageVocabularies(root) {
  const terms = new Map()
  const read  = []
  for (const reg of PACKAGE_REGISTERS) {
    const file = join(root, reg.file)
    let rows = null
    try {
      rows = existsSync(file) ? reg.read(readFileSync(file, 'utf8')) : null
    } catch {
      rows = null
    }
    read.push({ owner: reg.owner, file: reg.file, terms: rows ? rows.size : 0, found: !!rows })
    if (!rows) continue
    for (const [key, row] of rows) {
      const entry = { ...row, status: 'blessed', source: reg.file, owner: reg.owner }
      if (!terms.has(key)) terms.set(key, entry)
      // The corpus folds a plural into its singular when both were seen, so the
      // row is `Step` where the vocabulary says `Steps` and an exact lookup misses
      // — which is every plural term css ships (`Steps`, `Tabs`, `Facts`) and no
      // singular one, so the gap was invisible from the terms that worked. The
      // alias is the fold's own function, asked here rather than re-spelled.
      const singular = singularize(key)
      if (singular !== key && !terms.has(singular)) terms.set(singular, entry)
    }
  }
  return { terms, read }
}

// ─── the declared languages ───────────────────────────────────────────────────
//
// `.lite` is read from its own committed catalog, which asserts its completeness
// against the parser. Mesa has no catalog, so its words are GREPPED and say so —
// a grep finds `mesa:frobnicate` in a fixture and cannot tell it from a real
// block. The confidence is carried per row rather than averaged away, because
// this gap is the thing FJS-1211 is filed about.

function liteWords(root) {
  const file = join(root, 'packages/litestone/catalog.snapshot.md')
  if (!existsSync(file)) return []
  const out = []
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const cell = line.match(/^\|\s*`([^`]+)`/)
    if (cell) out.push({ word: cell[1], source: 'catalog.snapshot.md', confidence: 'declared', owner: 'litestone' })
  }
  return out
}

function mesaWords(root) {
  const declared = mesaElements(root)
  const dirs = ['packages/mesa/src', 'packages/sierra/src']
    .map(rel => join(root, rel)).filter(existsSync)
  if (!dirs.length) return []

  // Usage counts come from the source; the LIST does not. A grep over prose
  // answers `mesa:frobnicate` — the compiler's own example of a name that does
  // not exist — and `mesa:line`, which is a source location. A vocabulary that
  // holds its own counter-example is worse than one that is short.
  const seen = new Map()
  for (const dir of dirs) {
    for (const path of walk(dir)) {
      const dot = path.lastIndexOf('.')
      if (!SOURCE_EXT.has(path.slice(dot))) continue
      for (const hit of readFileSync(path, 'utf8').matchAll(/\bmesa:([a-zA-Z][a-zA-Z0-9]*)/g)) {
        seen.set(hit[1], (seen.get(hit[1]) ?? 0) + 1)
      }
    }
  }

  if (!declared.length) {
    // Both declarations moved or were renamed. Answering the grep is the honest
    // fallback and `grepped` on every row is what says so on the page — a
    // silently empty language tab would read as Mesa having no words at all.
    return [...seen].map(([name, count]) => ({
      word: `mesa:${name}`, count, source: 'packages/mesa/src', confidence: 'grepped', owner: 'mesa',
    }))
  }

  return declared.map(d => ({
    word: `mesa:${d.name}`,
    count: seen.get(d.name) ?? 0,
    source: d.source,
    confidence: 'declared',
    owner: d.owner,
  }))
}

// The `mesa:` namespace has TWO owners and a grep cannot tell you that.
// `MESA_ELEMENTS` in mesa's compiler is what the compiler knows and is the same
// array its typo error prints; `mesa:slot` is Sierra's, rewritten away before
// the compiler ever sees the tag. Both are read as TEXT rather than imported:
// the cli depends on neither package, and importing a compiler to ask it for
// nine strings would make it depend on both.
function mesaElements(root) {
  const out = []

  const compiler = join(root, 'packages/mesa/src/compiler.js')
  if (existsSync(compiler)) {
    const match = readFileSync(compiler, 'utf8').match(/export const MESA_ELEMENTS = \[([^\]]*)\]/)
    for (const m of match?.[1].matchAll(/'([a-zA-Z][a-zA-Z0-9]*)'/g) ?? []) {
      out.push({ name: m[1], owner: 'mesa', source: 'packages/mesa/src/compiler.js' })
    }
  }

  const slots = join(root, 'packages/sierra/src/build/slot-rewrite.js')
  if (existsSync(slots)) {
    const match = readFileSync(slots, 'utf8').match(/export const MESA_SLOT_TAG = 'mesa:([a-zA-Z][a-zA-Z0-9]*)'/)
    if (match) out.push({ name: match[1], owner: 'sierra', source: 'packages/sierra/src/build/slot-rewrite.js' })
  }

  return out
}

// ─── the api lens ─────────────────────────────────────────────────────────────
//
// Declaration sites only. A re-export would count the same name twice and make
// spread a measure of how many barrels a package has.

const EXPORT_RX = /^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm

function apiTerms(root, packages) {
  const rows = new Map()

  for (const pkg of packages) {
    const dir = join(root, 'packages', pkg, 'src')
    const entries = entryTargets(join(root, 'packages', pkg))

    // `@frontierjs/ui` has no `src/` at all — its components ARE the package —
    // so the walk below must not be what decides whether the package is read.
    for (const path of existsSync(dir) ? walk(dir) : []) {
      const dot = path.lastIndexOf('.')
      if (!SOURCE_EXT.has(path.slice(dot))) continue
      if (/\.(test|spec)\./.test(path)) continue

      const rel  = relative(root, path)
      const text = readFileSync(path, 'utf8')
      for (const hit of text.matchAll(EXPORT_RX)) {
        const name = hit[1]
        const row  = rows.get(name) ?? { term: name, count: 0, owners: new Set(), files: [], entry: false, byOwner: new Map() }
        row.count += 1
        row.owners.add(pkg)
        row.byOwner.set(pkg, (row.byOwner.get(pkg) ?? 0) + 1)
        if (row.files.length < 12) row.files.push(rel)
        if (entries.has(rel)) row.entry = true
        rows.set(name, row)
      }
    }

    // A Mesa component is an identifier that is never written as an export: the
    // FILE is the declaration and the caller types the basename. Without this
    // pass `EmptyState`, `StatCard` and `FilterBar` reach the prose scan with
    // nothing to say they are code, and land in the concepts table as though
    // somebody had coined them.
    for (const path of walk(join(root, 'packages', pkg))) {
      if (!path.endsWith('.mesa')) continue
      if (/[\\/](test|tests|fixtures|example)[\\/]/.test(path)) continue
      const name = path.slice(path.lastIndexOf('/') + 1, -'.mesa'.length)
      if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) continue
      const rel = relative(root, path)
      const row = rows.get(name) ?? { term: name, count: 0, owners: new Set(), files: [], entry: false, byOwner: new Map() }
      row.count += 1
      row.owners.add(pkg)
      row.byOwner.set(pkg, (row.byOwner.get(pkg) ?? 0) + 1)
      if (row.files.length < 12) row.files.push(rel)
      rows.set(name, row)
    }
  }

  return [...rows.values()].map(finish)
}

// Every path a package's `exports`/`main`/`bin` map points at. A name declared
// in one of those files is reachable by an app; one declared anywhere else is
// this repo talking to itself, and the two should never be counted as one
// vocabulary.
function entryTargets(pkgDir) {
  const out  = new Set()
  const file = join(pkgDir, 'package.json')
  if (!existsSync(file)) return out

  let pkg
  try { pkg = JSON.parse(readFileSync(file, 'utf8')) } catch { return out }

  const add = (value) => {
    if (typeof value === 'string') {
      const path = join(pkgDir, value.replace(/^\.\//, ''))
      out.add(relative(pkgDir.split(`${sep}packages${sep}`)[0], path))
      return
    }
    if (value && typeof value === 'object') for (const v of Object.values(value)) add(v)
  }

  add(pkg.exports)
  add(pkg.main)
  add(pkg.module)
  add(pkg.bin)
  return out
}

// ─── the model ────────────────────────────────────────────────────────────────

function finish(row) {
  const owners = [...row.owners].sort()
  // A plain object, because the page recomputes spread and count from it when a
  // source is switched off — the model cannot know which sources a reader wants
  // to stop looking at, and rescanning per answer is the thing a page is for.
  const byOwner = Object.fromEntries([...(row.byOwner ?? new Map())].sort((a, b) => b[1] - a[1]))
  // The JOINT breakdown, `owner|kind`. Two separate tallies cannot answer the
  // page's question: switching markdown off has to recompute SPREAD as well as
  // count, and how many packages are left is only decidable from the pair.
  const byCell  = Object.fromEntries([...(row.byCell ?? new Map())].sort((a, b) => b[1] - a[1]))
  const byKind  = {}
  for (const [cell, n] of Object.entries(byCell)) {
    const kind = cell.slice(cell.lastIndexOf('|') + 1)
    byKind[kind] = (byKind[kind] ?? 0) + n
  }
  return { ...row, owners, byOwner, byCell, byKind, spread: owners.length }
}

export function collectTerms({ root }) {
  const architect = architectVocabulary(root)
  const authored  = authoredVocabulary(root)
  const pkgVocab = packageVocabularies(root)
  const blessed   = new Set(architect.blessed.map(w => w.toLowerCase()))
  const clarified = new Set(architect.clarified.map(w => w.toLowerCase()))
  const unnamed   = new Set(architect.notYetNamed.map(w => w.toLowerCase()))

  const packages = existsSync(join(root, 'packages'))
    ? readdirSync(join(root, 'packages'), { withFileTypes: true })
        .filter(e => e.isDirectory() && !SKIP_DIRS.has(e.name)).map(e => e.name)
    : []

  // A package's own name is vocabulary, but it is a NAME — it teaches you what
  // to import, never what a word means. Derived rather than listed so a new
  // package classifies itself.
  const product = new Set(packages.map(p => p[0].toUpperCase() + p.slice(1)))
  product.add('Frontier'); product.add('FrontierJS'); product.add('Fli')

  const language = new Map()
  for (const row of liteWords(root)) language.set(row.word.toLowerCase(), { ...row, lens: 'lite' })
  for (const row of mesaWords(root)) language.set(row.word.toLowerCase(), { ...row, lens: 'mesa' })

  // ── prose pass ──
  //
  // Two things are counted in one read of each file. A second pass per term was
  // tried and is what made this slow: 52 forbidden words over 737 documents is
  // 38,000 reads for an answer the first pass already holds.
  const concepts = new Map()
  const droppedWords = new Map()
  const docs     = []

  // A term can be more than one word — `Data realm` is vocabulary where `data`
  // alone is too generic to be any. Both authored halves may name one: § 2's
  // `Gate ladder` and `Chain of Responsibility`, and any VOCABULARY.md row with
  // a space in it. They are SCANNED rather than discovered, because a phrase is
  // a claim somebody makes; what the scan does on its own is propose
  // candidates, below.
  const phrases = new Map([...new Set([
    ...architect.blessed.filter(w => w.includes(' ')),
    ...[...authored.values()].map(r => r.term).filter(w => w.includes(' ')),
  ])].map(w => [w, { term: w, count: 0, owners: new Set(), byOwner: new Map(), byCell: new Map(), files: new Map() }]))

  // Every adjacent pair the prose actually writes, so a phrase nobody has named
  // can be FOUND rather than thought of. Both halves must survive the drop
  // list, which is what keeps `the Data` and `Data is` out of it.
  const pairs = new Map()

  const byKind = Object.fromEntries(KINDS.map(k => [k, 0]))

  for (const path of walk(root)) {
    const dot  = path.lastIndexOf('.')
    const kind = KIND_BY_EXT.get(path.slice(dot))
    if (!kind) continue
    // The authored vocabulary is a list OF terms, not prose that uses them —
    // counting it would let a word gain spread by being labelled, which is the
    // measurement grading its own input.
    const rel = relative(root, path)
    if (rel === 'VOCABULARY.md') continue

    const raw = readFileSync(path, 'utf8')
    if (isGenerated(rel, raw)) continue

    docs.push(rel)
    byKind[kind] += 1
    const owner = ownerOf(root, path)
    const cell  = `${owner}|${kind}`
    // § 2 is the doctrine's own list OF terms, and a phrase is matched as
    // plain text, so leaving it in lets `Gate ladder` gain a use by being
    // blessed — the same measurement-grades-its-own-input that keeps
    // VOCABULARY.md out of the corpus entirely. The rest of ARCHITECT.md is
    // ordinary prose and stays.
    //
    // `proseOf` strips what a MARKDOWN reader would not say out loud. A source
    // file has no such layer — it is read whole, which is the trade the kind
    // exists to let a reader undo.
    const text = kind === 'markdown'
      ? proseOf(rel === 'ARCHITECT.md' ? withoutSectionTwo(raw) : raw)
      : raw

    for (const [word, phrase] of phrases) {
      const hits = text.match(new RegExp(`\\b${word.replace(/\s+/g, '\\s+')}\\b`, 'gi'))
      if (!hits) continue
      phrase.count += hits.length
      phrase.owners.add(owner)
      phrase.byOwner.set(owner, (phrase.byOwner.get(owner) ?? 0) + hits.length)
      phrase.byCell.set(cell, (phrase.byCell.get(cell) ?? 0) + hits.length)
      phrase.files.set(rel, (phrase.files.get(rel) ?? 0) + hits.length)
    }

    for (const hit of text.matchAll(PAIR_RX)) {
      const head = hit[1]
      const tail = hit[2]
      if (dropped(head) || dropped(tail)) continue
      if (COMMON.has(head) || COMMON.has(tail.replace(/^./, c => c.toUpperCase()))) continue
      if (verbish(tail) || JOINERS.has(tail.toLowerCase())) continue
      const pair = `${head} ${tail}`
      const row  = pairs.get(pair) ?? { term: pair, count: 0, owners: new Set() }
      row.count += 1
      row.owners.add(owner)
      pairs.set(pair, row)
    }

    for (const hit of text.matchAll(TERM_RX)) {
      const term = hit[1]
      // A plural is dropped with its singular. The fold below cannot do it:
      // it merges into a HOST row, and a dropped word leaves none, so `Views`
      // and `Requests` would survive as terms of their own.
      const lower = term.toLowerCase()
      if (dropped(term)) {
        droppedWords.set(term, (droppedWords.get(term) ?? 0) + 1)
        continue
      }
      const row  = concepts.get(term) ?? { term, count: 0, owners: new Set(), files: new Map(), byOwner: new Map(), byCell: new Map() }
      row.count += 1
      row.owners.add(owner)
      row.byOwner.set(owner, (row.byOwner.get(owner) ?? 0) + 1)
      row.byCell.set(cell, (row.byCell.get(cell) ?? 0) + 1)
      row.files.set(rel, (row.files.get(rel) ?? 0) + 1)
      concepts.set(term, row)
    }
  }

  // ── plurals fold into their singular ──
  //
  // `Users`, `Resources` and `Releases` are not separate vocabulary and are not
  // noise either, so neither keeping nor excluding them is right. A plural folds
  // only when the SINGULAR was also seen: `Steps` merges into `Step`, while a
  // word that merely ends in an s and stands alone is left exactly as written.
  for (const [term, row] of [...concepts]) {
    const singular = singularize(term)
    if (singular === term) continue
    const host = concepts.get(singular)
    if (!host) continue
    host.count += row.count
    for (const owner of row.owners) host.owners.add(owner)
    for (const [owner, n] of row.byOwner) host.byOwner.set(owner, (host.byOwner.get(owner) ?? 0) + n)
    for (const [cell,  n] of row.byCell)  host.byCell.set(cell,   (host.byCell.get(cell)  ?? 0) + n)
    for (const [file, n] of row.files) host.files.set(file, (host.files.get(file) ?? 0) + n)
    concepts.delete(term)
  }

  // A named phrase is a term and belongs in the same table as the words. It
  // joins AFTER the fold, which is a rule about a trailing s on one word.
  for (const phrase of phrases.values()) {
    if (!phrase.count) continue
    concepts.set(phrase.term, phrase)
  }

  const api = apiTerms(root, packages)
    .sort((a, b) => b.spread - a.spread || b.count - a.count || a.term.localeCompare(b.term))

  // An identifier is not a concept somebody coined, and a compound is how you
  // tell: `EmptyState` is the component a screen mounts, while `Empty state` is
  // the condition it handles, and only the second is vocabulary. A one-word
  // identifier is left alone — `Plugin`, `Channel` and `Store` are English this
  // framework also happens to export, and § 2 rules two of them.
  const declared = new Set(api.map(r => r.term))
  const compound = term => /[a-z][A-Z]/.test(term)

  const conceptRows = [...concepts.values()].map((row) => {
    const lower = row.term.toLowerCase()
    const klass = row.term.includes(' ')
      ? 'concept'
      : language.has(lower)
      ? 'language'
      : declared.has(row.term) &&
        compound(row.term) &&
        !blessed.has(lower) &&
        !authored.has(lower)
      ? 'api'
      : product.has(row.term)
      ? 'product'
      : EXTERNAL.has(row.term)
      ? 'external'
      : COMMON.has(row.term)
      ? 'common'
      : 'concept'
    // § 2 is the doctrine and outranks the file, which is what the file says
    // about itself: where the two disagree, VOCABULARY.md is the stale one.
    // A package vocabulary is one rung below both, which is §VII's own ladder —
    // invariant, ruling, map, package document — so a word the root file and a
    // package both name is the root file's, and nothing here can widen a term
    // the doctrine already ruled on.
    const label = placed(authored.get(lower), pkgVocab.terms.get(lower))
    const status = blessed.has(lower)
      ? 'blessed'
      : clarified.has(lower)
      ? 'clarified'
      : unnamed.has(lower)
      ? 'not-yet-named'
      : label
      ? label.status
      : 'unnamed'
    const files = [...row.files]
      .sort((a, b) => b[1] - a[1])
      .slice(0, 12)
      .map(([file, count]) => ({ file, count }))
    return finish({ ...row, class: klass, status, files, label })
  }).sort((a, b) => b.spread - a.spread || b.count - a.count || a.term.localeCompare(b.term))

  // ── the forbidden column ──
  //
  // Counted as a TERM, never as a word. A first cut counted every occurrence
  // case-insensitively and reported `table` 2,490 times — markdown tables — and
  // `service`, `state` and `build` in the thousands, which is English and not
  // drift. What § 2 forbids is using the word for the CONCEPT, and this house
  // capitalizes a concept mid-sentence, so that is the only occurrence worth
  // reporting. The lowercase uses are real and are not decidable from here.
  // A word can sit in both columns of § 2 — `Channel` is blessed for a broadcast
  // set and refused for a delivery medium, `Hook` is blessed for the tier that
  // can halt and refused for the two that cannot. The table forbids a SENSE and
  // this scan sees a spelling, so a word § 2 also blesses is not evidence of
  // anything and is left out rather than reported as drift.
  const byTerm = new Map(conceptRows.map(r => [r.term.toLowerCase(), r]))

  // The audit's counts are PROSE counts. Every question in it is about the
  // authored vocabularies, which are prose, and the widened corpus moves all of
  // them at once with nothing saying so — measured on the first run over code:
  // `unlabelled` went 0 → 123, dead doctrine 4 → 0 (a blessed word is never
  // rare once identifiers count), and the forbidden column 18 → 28.
  //
  // A phrase row reaches here before `finish` has run on it, so its breakdown is
  // still a Map. Both shapes are taken rather than converted at the call sites,
  // because a phrase whose count is 0 never enters `concepts` at all and the
  // caller genuinely has the raw row in hand.
  const cellsOf = (row) => {
    const b = row?.byCell
    return b instanceof Map ? [...b] : Object.entries(b ?? {})
  }
  const prose = (row) => {
    let n = 0
    for (const [cell, hits] of cellsOf(row)) if (cell.endsWith('|markdown')) n += hits
    return n
  }
  const proseSpread = (row) => {
    const owners = new Set()
    for (const [cell, hits] of cellsOf(row))
      if (hits > 0 && cell.endsWith('|markdown')) owners.add(cell.slice(0, cell.lastIndexOf('|')))
    return owners.size
  }

  const forbidden = [...new Set(architect.forbidden.map(w => w.toLowerCase()))]
    .filter(w => !blessed.has(w))
    .map((word) => {
      const row = byTerm.get(word)
      return {
        term: word,
        count: prose(row),
        spread: proseSpread(row),
        files: row?.files ?? [],
      }
    })
    .filter(r => r.count > 0)
    .sort((a, b) => b.count - a.count)

  const languageRows = [...language.values()].map(row => ({
    term: row.word, lens: row.lens, source: row.source, confidence: row.confidence,
    count: row.count ?? 1, owner: row.owner,
    // A language word is declared in exactly one package, so its spread is 1 and
    // its breakdown is that package — which is what lets the source toggles
    // reach this tab at all. Without it the rows were inert while every other
    // tab responded, and an inert control reads as a broken one.
    spread: 1, byOwner: { [row.owner]: row.count ?? 1 },
  })).sort((a, b) => a.lens.localeCompare(b.lens) || a.term.localeCompare(b.term))

  const conceptsOnly = conceptRows.filter(r => r.class === 'concept')

  // ── the audit is asked of the PROSE, and stays that way ──
  //
  // Every question in it is about the authored vocabularies, which are prose and
  // were seeded from prose at spread 4. Asking them of the widened corpus would
  // change what each one MEANS with nothing saying so: the first run over code
  // put Math, Record and SessionContext into *not in VOCABULARY.md* and took it
  // from 0 rows to 123, which is not 123 words somebody forgot to define. The
  // audit is the list a reader acts on, so it keeps the corpus it was
  // calibrated on; the tabs beside it are where the wider one is read.
  const conceptsProse = narrowToKinds(conceptsOnly, new Set(['markdown']))

  // Every source a concept was read from, with how much of the prose it is.
  // Ordered by weight, because the one a reader wants to switch off first is
  // usually the loudest — `IDEAS/` is design records for work not started, and
  // its vocabulary is proposals rather than the framework.
  //
  // Counted PER LENS rather than once, because the same chip means different
  // amounts on different tabs and a single number is wrong on two of the three:
  // `IDEAS/` is a fifth of the prose and holds no source file at all, so a chip
  // reading `IDEAS 2431` on the API tab describes nothing the reader is looking
  // at. A lens where a source has nothing is a real answer and the chip says so.
  const tally = new Map()
  const add = (lens, rows) => {
    for (const r of rows) {
      for (const [owner, n] of Object.entries(r.byOwner ?? {})) {
        const row = tally.get(owner) ?? { name: owner, concept: 0, api: 0, language: 0 }
        row[lens] += n
        tally.set(owner, row)
      }
    }
  }
  add('concept', conceptRows)
  add('api', api)
  add('language', languageRows)

  const sources = [...tally.values()]
    .map(r => ({ ...r, total: r.concept + r.api + r.language }))
    .sort((a, b) => b.concept - a.concept || b.total - a.total)

  return {
    root,
    generated: new Date().toISOString(),
    corpus: { docs: docs.length, packages: packages.length, byKind },
    architect,
    counts: {
      concept: conceptsOnly.length,
      product: conceptRows.filter((r) => r.class === 'product').length,
      external: conceptRows.filter((r) => r.class === 'external').length,
      common: conceptRows.filter((r) => r.class === 'common').length,
      language: languageRows.length,
      labelled: conceptRows.filter((r) => r.class === 'concept' && r.label).length,
      authored: authored.size,
      packageNamed: conceptRows.filter((r) => r.class === 'concept' && r.label?.source)
        .length,
      api: api.length,
      apiEntry: api.filter((r) => r.entry).length,
      dropped: droppedWords.size,
      droppedHits: [...droppedWords.values()].reduce((a, b) => a + b, 0)
    },
    sources,
    vocabularies: pkgVocab.read,
    concepts: conceptRows,
    language: languageRows,
    api,
    audit: {
      // Dead doctrine: § 2 blesses the word and the repo barely says it.
      blessedUnused: architect.blessed
        .map((word) => {
          const phrase = phrases.get(word)
          if (phrase) return { term: word, count: prose(phrase), spread: proseSpread(phrase) }
          const row = byTerm.get(word.toLowerCase())
          return { term: word, count: prose(row), spread: proseSpread(row) }
        })
        .filter((r) => r.count < 5),
      // Vocabulary that exists and nobody defined.
      unnamedCommon: conceptsProse
        .filter((r) => r.status === 'unnamed' && r.spread >= 4)
        .slice(0, 60),
      // What a spread-4 term is missing from the authored file. The seed was
      // taken at that bar, so a row here is either a word that has since spread
      // or one somebody deleted from VOCABULARY.md.
      unlabelled: conceptsProse.filter(
        (r) => r.spread >= 4 && !r.label && !blessed.has(r.term.toLowerCase())
      ),
      forbiddenUsed: forbidden.filter((r) => r.count > 0),
      // The root vocabulary has SEEN the word and not decided, and a package
      // vocabulary has. `open` is not an answer — the file says so itself, *seen
      // and not yet decided, the seeded default* — so it outranks a package
      // definition on the ladder while carrying less than one, which is the one
      // place the precedence reads as an answer and is not.
      //
      // Not resolved by letting the package win. Most of these are one spelling
      // over two realms — a Table is a `<table>` in css and a database table in
      // litestone, a Field is a control and a column — which is § 2's own
      // `Channel` case, and a reader needs to be shown both rather than handed
      // whichever vocabulary spoke last.
      undecidedButDefined: conceptsProse
        .filter((r) => r.label?.status === 'open' && pkgVocab.terms.has(r.term.toLowerCase()))
        .map((r) => {
          const pkg = pkgVocab.terms.get(r.term.toLowerCase())
          return {
            term: r.term,
            count: r.count,
            spread: r.spread,
            owner: pkg.owner,
            means: pkg.means
          }
        }),
      // A row the scan can no longer see. Dropping a word is a one-line edit
      // over here and it silently orphans a definition over there — the file
      // goes on carrying a term nothing measures, which is the one failure
      // authored-plus-generated is supposed to make impossible.
      definedUnseen: [...authored.values()]
        .filter((r) => !byTerm.has(r.term.toLowerCase()))
        .map((r) => ({ term: r.term, status: r.status, means: r.means })),
      // Pairs the prose writes as one thing and nobody has named. A candidate
      // list rather than a finding: promoting one is a row in VOCABULARY.md,
      // and until somebody writes that row it is two words that travel
      // together, which is not the same claim.
      phraseCandidates: [...pairs.values()]
        .filter((r) => r.owners.size >= 3 && r.count >= 8 && !phrases.has(r.term))
        // What is left after the shape filters is a sentence wearing a term's
        // clothes: a participle in front (`Verified state`) or a verb behind
        // (`Litestone emits`). A trailing s is only a plural if the singular is
        // a word this repo also uses on its own.
        .filter((r) => {
          const [head, tail] = r.term.split(' ')
          if (/(?:ed|ing)$/.test(head) && !byTerm.has(head.toLowerCase())) return false
          const singular = singularize(tail.toLowerCase())
          return singular === tail.toLowerCase() || byTerm.has(singular)
        })
        .map((r) => ({ term: r.term, count: r.count, spread: r.owners.size }))
        .sort((a, b) => b.spread - a.spread || b.count - a.count)
        .slice(0, 60)
    }
  }
}

// ─── presentation: the terminal ───────────────────────────────────────────────

// Narrowing to a set of file kinds, in the terminal, by the same arithmetic the
// page's chips do — one implementation would be better and cannot be had: that
// one runs in a browser over data attributes. So the two are kept to the same
// shape (recompute count, recompute spread from the owners left) and a change
// to either is owed to the other.
function narrowToKinds(rows, keep) {
  return rows
    .map((row) => {
      const owners = new Set()
      let count = 0
      for (const [cell, n] of Object.entries(row.byCell ?? {})) {
        const bar = cell.lastIndexOf('|')
        if (bar < 0 || !keep.has(cell.slice(bar + 1))) continue
        count += n
        owners.add(cell.slice(0, bar))
      }
      return { ...row, count, spread: owners.size }
    })
    .filter((r) => r.count > 0)
    .sort((a, b) => b.spread - a.spread || b.count - a.count || a.term.localeCompare(b.term))
}

export function renderList(model, { limit = 40, lens = 'concept', kinds = null } = {}) {
  const out = []
  const pad = (s, n) => String(s).padEnd(n)

  out.push('')
  out.push(`  ${model.corpus.docs} doc(s) · ${model.corpus.packages} package(s)`)
  out.push(`  ${KINDS.map((k) => `${k} ${model.corpus.byKind?.[k] ?? 0}`).join(' · ')}`)
  out.push('')
  out.push(
    `  concept ${model.counts.concept}   language ${model.counts.language}   api ${model.counts.api} (${model.counts.apiEntry} at an entry point)`
  )
  out.push(
    `  classified out — product ${model.counts.product} · external ${model.counts.external} · common ${model.counts.common}`
  )
  out.push(
    `  dropped as English — ${model.counts.dropped} word(s), ${model.counts.droppedHits} occurrence(s)`
  )
  out.push(
    `  VOCABULARY.md defines ${model.counts.authored} · ${model.audit.unlabelled.length} term(s) at spread 4+ unlisted`
  )
  // The count per vocabulary, not a total. A vocabulary that stopped resolving
  // returns every one of its terms to `unnamed`, which is what a package that
  // named nothing also looks like — so the number that separates them is
  // printed, and `not found` is printed rather than omitted.
  for (const reg of model.vocabularies ?? [])
    out.push(`  ${reg.file} ${reg.found ? `defines ${reg.terms}` : 'NOT FOUND'}`)
  if (kinds) out.push(`  narrowed to ${[...kinds].join(', ')} — count and spread are RECOMPUTED, not filtered`)
  out.push('')

  // The api and language lenses read DECLARATIONS rather than the corpus, so a
  // file-kind narrowing has nothing to say about them and is not applied.
  const concepts = model.concepts.filter((r) => r.class === 'concept')
  const rows =
    lens === 'api'
      ? model.api
      : lens === 'language'
      ? model.language
      : kinds
      ? narrowToKinds(concepts, kinds)
      : concepts

  if (lens === 'language') {
    out.push(`  ${pad('term', 26)}${pad('lens', 8)}confidence`)
    for (const r of rows.slice(0, limit))
      out.push(`  ${pad(r.term, 26)}${pad(r.lens, 8)}${r.confidence}`)
  } else {
    out.push(
      `  ${pad('term', 26)}${pad('spread', 8)}${pad('count', 8)}${
        lens === 'api' ? 'entry' : 'status'
      }`
    )
    for (const r of rows.slice(0, limit)) {
      out.push(
        `  ${pad(r.term, 26)}${pad(r.spread, 8)}${pad(r.count, 8)}${
          lens === 'api' ? (r.entry ? 'yes' : '') : r.status
        }`
      )
    }
  }

  out.push('')
  out.push(`  ${rows.length} row(s), ${Math.min(limit, rows.length)} shown`)
  out.push('')
  return out.join('\n')
}

