// ─── what the corpus is made of ───────────────────────────────────────────────
//
// Four KINDS, because *is this word in the documents or in the code* is a
// different question from *which package says it*, and the page lets a reader
// subtract either. A term written about at length and named by nothing is the
// shape worth finding, and it is invisible while the corpus is markdown alone.
//
// **A source file is read WHOLE**, comments and code together. That is a
// deliberate trade and it costs something: `Map`, `Set` and every class name
// rank as concepts, and a term the api lens already counts is counted here too.
// The page says so where the numbers are, rather than leaving a reader to
// wonder why `String` outranks `Resource`.
const KIND_BY_EXT = new Map([
  ['.md',    'markdown'],
  ['.ts',    'code'],  ['.js',   'code'], ['.mjs', 'code'], ['.mts', 'code'],
  ['.mesa',  'framework'], ['.lite', 'framework'],
  ['.css',   'web'],  ['.html', 'web'],
])
export const KINDS = ['markdown', 'code', 'framework', 'web']

const DOC_EXT    = new Set(['.md'])
const SOURCE_EXT = new Set(['.js', '.ts', '.mjs', '.mts'])

// Output this workspace WROTE is not prose somebody wrote, and reading it is the
// measurement grading its own input — which is already why VOCABULARY.md is out
// of the corpus. There is no single marker, so three are asked: the committed
// snapshots carry `.snapshot.` in the name, `ws:atlas --live` carries a
// generator line and not the name, and THIS COMMAND'S OWN PAGE carries neither
// by design — it is ungated, so it has no generator line to be rechecked by.
// At ~2 MB that page is the largest file in the tree matching a corpus
// extension, and every term on it would be counted a second time.
const GENERATED_FILES = new Set(['repo-terms.html', 'registers.html'])

function isGenerated(rel, raw) {
  return /\.snapshot\./.test(rel)
      || GENERATED_FILES.has(rel)
      || /generated by:/.test(raw.slice(0, 400))
}

function walk(dir, out = []) {
  let entries
  try { entries = readdirSync(dir, { withFileTypes: true }) } catch { return out }

  for (const entry of entries) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) {
      // The skip list names OUTPUT directories, and one of them is a legal
      // source directory name: sierra's compile-time rewriters live in
      // `src/build/`, so skipping `build` everywhere hid `mesa:slot` and every
      // identifier that package declares there.
      if (SKIP_DIRS.has(entry.name) && !/[\\/]src[\\/]/.test(`${path}/`)) continue
      walk(path, out)
      continue
    }
    if (!entry.isFile()) continue
    const dot = entry.name.lastIndexOf('.')
    if (dot < 0) continue
    out.push(path)
  }
  return out
}

// Which package a file belongs to. The bucket is what `spread` counts, so a
// file outside any package still needs one — `root` is a real answer and an
// empty string would silently merge every such file into one.
function ownerOf(root, path) {
  const rel   = relative(root, path)
  const parts = rel.split(sep)
  if (parts[0] === 'packages' && parts.length > 1) return parts[1]
  if (parts.length > 1) return parts[0]
  return 'root'
}

// ─── the prose reader ─────────────────────────────────────────────────────────
//
// Everything a reader would not say out loud comes out first. A term inside a
// code span is an identifier and belongs to the api lens, not the concept one —
// counting it in both is how `createResource` would rank as a concept.

function proseOf(text) {
  return splitFrontmatter(text).body
    .replace(/```[\s\S]*?```/g, ' ')                 // fenced code
    .replace(/~~~[\s\S]*?~~~/g, ' ')
    .replace(/`[^`\n]*`/g, ' ')                      // inline code
    .replace(/<!--[\s\S]*?-->/g, ' ')                // html comments
    .replace(/\]\([^)\s]*\)/g, '] ')                 // link targets, not labels
    .replace(/https?:\/\/\S+/g, ' ')
    .replace(/<[^>]+>/g, ' ')                        // raw html
}

// Mid-sentence capitalization is the signal. A word at a sentence start is
// capitalized by grammar and says nothing; one in the middle was capitalized by
// somebody meaning a Thing. Requiring a lowercase second character drops the
// house style's SHOUTED emphasis, which is not vocabulary either.
//
// Only a lowercase letter, a digit, a comma or a close bracket may precede. A
// dash, colon or semicolon was tried and reverted: this house writes them to
// open a new clause, so the word after one is capitalized by grammar and the
// scan filled with `An`, `Whether` and `For`.
const TERM_RX = /[a-z0-9),]\s+([A-Z][a-z][A-Za-z]*)\b/g

// A pair the prose writes as one thing: a capitalized head and the word after
// it, either capitalized (`Data Realm`) or an ordinary noun (`Gate ladder`).
// Candidates only — what makes a pair a TERM is somebody saying so.
const PAIR_RX = /\b([A-Z][a-z][A-Za-z]*)\s+([A-Z][a-z][A-Za-z]*|[a-z]{3,})\b/g

// A pair whose second half is doing something is a sentence, not a term:
// `Litestone emits`, `Verified against`, `Derived rather`. Participles and
// adverbs are shape; the joiners are a short list because the frequent ones are
// already dropped English.
const JOINERS = new Set([
  'against', 'rather', 'than', 'toward', 'towards', 'via', 'per', 'unless',
  'until', 'though', 'although', 'upon', 'onto', 'within', 'across', 'beyond',
  'despite', 'during', 'whenever', 'wherever', 'whereas', 'therefore', 'instead',
])

function verbish(word) {
  return /(?:ed|ing|ly)$/.test(word) && word === word.toLowerCase()
}

// One drop test for both scans. A plural is dropped with its singular, since
// the fold merges into a HOST row and a dropped word leaves none.
function dropped(word) {
  const lower = word.toLowerCase()
  return DROPPED.has(lower) || DROPPED.has(singularize(lower))
}

