// The themes `@frontierjs/css` ships, and the light/dark pair is the package's
// own rather than a guess: `field` is an ink ground written for the pages a
// project generates about itself, and `press` says in its header that it is the
// same discipline on the opposite ground. A theme name is not a luminance claim
