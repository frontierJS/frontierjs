// ─── terms.js — what vocabulary does this workspace ask a newcomer to learn? ──
//
// One model, three presentations. The question it answers is the size and the
// shape of the vocabulary: how many words must somebody hold to read this repo,
// which of them the doctrine blesses, and which of them nothing has ever named.
//
// ── Three vocabularies, never one number ─────────────────────────────────────
//
// A single frequency count mixes things that are learned three different ways
// and the average describes none of them.
//
//   concept   — Model, Service, Resource, Release. A mental model is built from
//               these. Tens of them. This is the one worth auditing.
//   language  — what a `.lite` or `.mesa` file may hold. Declared, countable,
//               and already gated for `.lite` (`catalog.snapshot.md`).
//   api       — identifiers a developer types. Looked up, not memorized, so the
//               count that matters is how far each one SPREADS.
//
// ── Classification, never a silent exclude ───────────────────────────────────
//
// Measured before this was written: the noise in a prose scan is not stop words
// — it is proper nouns. `Vite`, `Chrome`, `Java` and `Prisma` all outrank
// `Resource`. So nothing is dropped. Every term is CLASSIFIED and the classes
// that are not concepts can be looked at, because a word landing in the wrong
// class is the failure this file can actually have, and a dropped word leaves
// nothing behind to notice.
//
// ── Spread over count ────────────────────────────────────────────────────────
//
// A term in twelve packages is core vocabulary. A term with three hundred hits
// in one file is local jargon. Raw frequency ranks the second above the first.
//
// ── Not a snapshot ───────────────────────────────────────────────────────────
//
// The written page carries no `generated by:` line and is not named
// `*.snapshot.*`, so the `snapshots` CI phase does not adopt it. That is
// deliberate while the exclude lists are still being refined — a gated artifact
// would fail the build on every tuning pass. The gated `ws:dictionary` is the
// thing this becomes once `ARCHITECT.md` § 2 settles ([FJS-1211](ISSUES.md)).

