const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c])

// A path the reader can open. `vscode://file/<absolute>` is the editor's own
// scheme, so the ABSOLUTE path has to be baked in — which means the written page
// is local to the machine that wrote it. That is already true of this page (it
// is ungated and gitignored) and is why the links are here rather than in a
// committed snapshot, where they would point at somebody else's home directory.
//
// No line number: the prose scan reads a document with its code spans and fences
// stripped out, so an offset into what it read is not an offset into the file.
function fileLink(root, rel, text = rel) {
  return `<a class="link" href="vscode://file${esc(root)}/${esc(rel)}">${esc(text)}</a>`
}

function row(cells, attrs = '') {
  return `<tr ${attrs}>${cells.map(c => `<td>${c}</td>`).join('')}</tr>`
}

function badgeFor(status) {
  const tone = status === 'blessed' ? 'success'
             : status === 'refused' ? 'danger'
             : status === 'unnamed' ? 'warning'
             : status === 'open'    ? 'warning'
             : status === 'not-yet-named' ? 'info'
             : ''
  return `<span class="badge ${tone}">${esc(status)}</span>`
}

function conceptTable(rows, root = '') {
  return `<div class="table-wrap"><table class="table striped dense">
    <thead><tr><th>term</th><th>spread</th><th>count</th><th>status</th><th>class</th><th>means</th><th>where</th></tr></thead>
    <tbody>${rows.map(r => row([
      `<strong>${esc(r.term)}</strong>`,
      `<span class="c-spread">${r.spread}</span>`,
      `<span class="c-count">${r.count}</span>`,
      badgeFor(r.status),
      `<span class="badge">${esc(r.class)}</span>`,
      r.label?.means
        ? esc(r.label.means)
        : '<span class="text-xs text-muted">—</span>',
      `<span class="text-xs text-muted">${r.files.slice(0, 3).map(f => fileLink(root, f.file)).join(' · ')}</span>`,
    ], `data-term="${esc(r.term.toLowerCase())}" data-class="${esc(r.class)}" data-status="${esc(r.status)}" data-spread="${r.spread}" data-count="${r.count}" data-owners="${Object.entries(r.byOwner).map(([o, n]) => `${esc(o)}:${n}`).join(';')}" data-cells="${Object.entries(r.byCell ?? {}).map(([c, n]) => `${esc(c)}:${n}`).join(';')}"`)).join('')}</tbody>
  </table></div>`
}

