    <div class="section-header"><h2 class="h5">Words § 2 forbids, used as terms</h2>
      <p class="text-xs text-muted">candidates, not verdicts — capitalized mid-sentence only, since the lowercase uses are ordinary English; a word § 2 also blesses is left out</p></div>
