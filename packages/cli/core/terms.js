// Backticks are forbidden in here — this string is itself inside a template
// literal, and one would close it and break the file's PARSE somewhere else.
const SCRIPT = `
const q = document.getElementById('q')
const panes = [...document.querySelectorAll('[data-tab]')]
const themePick = document.getElementById('theme')
const fSpread = document.getElementById('f-spread')
const fCount  = document.getElementById('f-count')
const fSpreadMax = document.getElementById('f-spread-max')
const fCountMax  = document.getElementById('f-count-max')
const fStatus = document.getElementById('f-status')
const fClass  = document.getElementById('f-class')
const shownAt = document.getElementById('shown')
const srcBoxes  = [...document.querySelectorAll('.src')]
const kindBoxes = [...document.querySelectorAll('.kind')]
const kindRow   = document.getElementById('kind-row')

// A row's spread and count are the WHOLE tree's answer. Switching a source off
// has to recompute both from the row's own breakdown rather than hide rows,
// because a term read 40 times in IDEAS/ and twice in packages/ is a different
// term once IDEAS/ is off, and a filter over the old numbers would keep it.
//
// The same is true one dimension over: *which concepts are in the CODE* is what
// switching markdown off asks, and it is a different ranking rather than a
// shorter list. So a concept row carries the JOINT breakdown, owner then kind,
// because spread is a count of owners and how many are left once a kind is off
// cannot be recovered from two separate tallies.
//
// An api or language row carries no kinds and is not a corpus scan at all: those
// lenses read DECLARATIONS, so a file-kind filter has nothing to say about them
// and they fall back to the owner breakdown rather than being emptied by it.
function recount() {
  const off     = new Set(srcBoxes.filter(b => !b.checked).map(b => b.value))
  const kindOff = new Set(kindBoxes.filter(b => !b.checked).map(b => b.value))
  for (const tr of document.querySelectorAll('tr[data-owners]')) {
    const cells = tr.dataset.cells
    const pairs = (cells || tr.dataset.owners || '').split(';').filter(Boolean)
      .map(p => { const at = p.lastIndexOf(':'); return [p.slice(0, at), Number(p.slice(at + 1))] })
    const owners = new Set()
    let count = 0
    for (const [key, n] of pairs) {
      const bar   = key.lastIndexOf('|')
      const owner = bar < 0 ? key : key.slice(0, bar)
      const kind  = bar < 0 ? null : key.slice(bar + 1)
      if (off.has(owner)) continue
      if (kind && kindOff.has(kind)) continue
      count += n
      owners.add(owner)
    }
    const spread = owners.size
    tr.dataset.spread = spread
    tr.dataset.count  = count
    const s = tr.querySelector('.c-spread'), c = tr.querySelector('.c-count')
    if (s) s.textContent = spread
    if (c) c.textContent = count
    // A term left with nothing is not in the reduced tree at all.
    tr.dataset.empty = pairs.length > 0 && count === 0 ? 'yes' : 'no'
  }
}

// The head script has already chosen; this only reflects that choice into the
// control and records a later one. Reading the class rather than the storage
// key keeps the two from disagreeing when nothing was ever saved.
function setTheme(name) {
  document.documentElement.className = 'theme-' + name
  themePick.value = name
  try { localStorage.setItem('fli.terms.theme', name) } catch (e) {}
}
themePick.value = (document.documentElement.className.match(/theme-([a-z]+)/) || [])[1] || themePick.value
themePick.addEventListener('change', () => setTheme(themePick.value))
const tabs  = [...document.querySelectorAll('[data-go]')]

// A chip's number is what that source contributes to the VISIBLE vocabulary.
// The IDEAS folder is a fifth of the prose and holds no source file at all,
// so one number across all three tabs would be wrong on two of them.
function retuneSources(lens) {
  for (const chip of document.querySelectorAll('.terms-sources .chip')) {
    const n = Number(chip.dataset[lens] || 0)
    chip.querySelector('.src-n').textContent = n
    chip.dataset.empty = n === 0 ? 'yes' : 'no'
    chip.title = n === 0 ? 'nothing on this tab comes from here' : ''
  }
}

function show(name) {
  for (const p of panes) p.hidden = p.dataset.tab !== name
  for (const t of tabs) t.classList.toggle('is-on', t.dataset.go === name)
  // The api and language lenses read declarations rather than the corpus, so
  // the kind chips would sit there doing nothing on every row.
  kindRow.hidden = name === 'api' || name === 'language'
  retuneSources(name)
  filter()
}

// One reader for every tab. A row declares term, status, spread and count, so a
// tab that ships a new column costs no filter code — and a tab whose rows have
// no spread declares 0 rather than omitting it, since a missing attribute and a
// zero would otherwise both read as NaN and hide the whole table.
function filter() {
  const needle = q.value.trim().toLowerCase()
  const spread = Number(fSpread.value) || 0
  const count  = Number(fCount.value) || 0
  const spreadMax = fSpreadMax.value === '' ? Infinity : Number(fSpreadMax.value)
  const countMax  = fCountMax.value === ''  ? Infinity : Number(fCountMax.value)
  const status = fStatus.value
  const klass  = fClass.value
  const pane   = panes.find(p => !p.hidden)
  if (!pane) return

  let shown = 0, total = 0
  for (const tr of pane.querySelectorAll('tbody tr')) {
    total++
    const hide =
      (needle.length > 0 && !(tr.dataset.term || '').includes(needle)) ||
      tr.dataset.empty === 'yes' ||
      Number(tr.dataset.spread || 0) < spread ||
      Number(tr.dataset.spread || 0) > spreadMax ||
      Number(tr.dataset.count || 0) < count ||
      Number(tr.dataset.count || 0) > countMax ||
      (status !== '' && tr.dataset.status !== status) ||
      (klass !== '' && tr.dataset.class !== klass)
    tr.hidden = hide
    if (!hide) shown++
  }
  shownAt.textContent = shown === total ? total + ' rows' : shown + ' of ' + total + ' rows'
}

for (const t of tabs) t.addEventListener('click', () => show(t.dataset.go))
for (const el of [q, fSpread, fCount, fSpreadMax, fCountMax, fStatus, fClass]) el.addEventListener('input', filter)
for (const el of [fStatus, fClass]) el.addEventListener('change', filter)
for (const box of srcBoxes)  box.addEventListener('change', () => { recount(); filter() })
for (const box of kindBoxes) box.addEventListener('change', () => { recount(); filter() })
document.getElementById('src-all').addEventListener('click', () => {
  const anyOff = srcBoxes.some(b => !b.checked)
  for (const b of srcBoxes) b.checked = anyOff
  recount(); filter()
})

document.getElementById('kind-all').addEventListener('click', () => {
  const anyOff = kindBoxes.some(b => !b.checked)
  for (const b of kindBoxes) b.checked = anyOff
  recount(); filter()
})
document.getElementById('f-clear').addEventListener('click', () => {
  q.value = ''; fSpread.value = '0'; fCount.value = '0'
  fSpreadMax.value = ''; fCountMax.value = ''; fStatus.value = ''; fClass.value = ''
  filter()
})
document.addEventListener('keydown', (e) => {
  if (e.key === '/' && document.activeElement !== q) { e.preventDefault(); q.focus() }
  if (e.key === 'Escape') { q.value = ''; filter() }
})

// The page opens on Concepts, and a chip that only learns its tab on the first
// tab CHANGE spends that whole first screen showing a number for a lens nobody
// picked.
retuneSources('concept')
filter()
`
