// deps.test.js — what core/deps.js reads out of a root: the declarations from
// each member's package.json, the installed versions from bun.lock, and the
// findings decidable without a registry. A real lockfile shape, written to a
// temp directory, because the lock's nesting rule is the part most easily
// got wrong.

import { describe, test, expect, beforeAll, afterAll } from 'bun:test'
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'fs'
import { join }   from 'path'
import { tmpdir } from 'os'

import { collectDeps, depsFindings, depsPayload, renderDepsSnapshot } from '../core/deps.js'

let ROOT

const write = (path, body) => {
  const full = join(ROOT, path)
  mkdirSync(join(full, '..'), { recursive: true })
  writeFileSync(full, typeof body === 'string' ? body : JSON.stringify(body, null, 2))
}

beforeAll(() => {
  ROOT = mkdtempSync(join(tmpdir(), 'fli-deps-'))
  write('package.json', { name: 'ws', private: true, workspaces: ['packages/*', 'app'],
                          devDependencies: { typescript: '^5.9.3' } })
  write('packages/kit/package.json', { name: '@x/kit', version: '1.0.0',
    dependencies: { '@x/core': 'workspace:*', 'css-tree': '^2.3.1' },
    peerDependencies: { typescript: '>=5.0.0', vite: '^8.0.0' } })
  write('packages/core/package.json', { name: '@x/core', version: '1.0.0', dependencies: { 'local-thing': 'file:../thing' } })
  // Edited after the last install: the lock below has no entry for `left-pad`.
  write('app/package.json', { name: 'app', private: true,
    dependencies: { '@x/kit': 'workspace:*', 'css-tree': '^3.0.0', 'left-pad': '^1.3.0' } })
  // JSONC, as bun writes it — trailing commas included.
  write('bun.lock', `{
  "lockfileVersion": 1,
  "workspaces": {
    "": { "name": "ws", "devDependencies": { "typescript": "^5.9.3", }, },
    "app": { "name": "app", "dependencies": { "css-tree": "^3.0.0", }, },
    "packages/core": { "name": "@x/core", },
    "packages/kit": { "name": "@x/kit", },
  },
  "packages": {
    "@x/kit": ["@x/kit@workspace:packages/kit"],
    "css-tree": ["css-tree@2.3.1", "", {}, "sha512-a"],
    "app/css-tree": ["css-tree@3.2.1", "", {}, "sha512-b"],
    "typescript": ["typescript@5.9.3", "", {}, "sha512-c"],
    "vite": ["vite@8.3.2", "", {}, "sha512-d"],
  },
}
`)
})

afterAll(() => { try { rmSync(ROOT, { recursive: true, force: true }) } catch {} })

describe('collectDeps', () => {
  test('members come from the lock, siblings and file: specs are not dependencies', () => {
    const r = collectDeps(ROOT)
    expect(r.name).toBe('ws')
    expect(r.members.map(m => m.path)).toEqual(['', 'app', 'packages/core', 'packages/kit'])
    expect(r.members.find(m => m.path === 'packages/kit').private).toBe(false)
    expect(r.deps.map(d => d.name)).toEqual(['css-tree', 'left-pad', 'typescript', 'vite'])
  })

  test('a nested lock entry wins for its member; everyone else gets the hoisted copy', () => {
    const css = collectDeps(ROOT).deps.find(d => d.name === 'css-tree')
    expect(css.uses.map(u => [u.member, u.installed])).toEqual([['@x/kit', '2.3.1'], ['app', '3.2.1']])
    expect(css.installed).toEqual(['2.3.1', '3.2.1'])
  })

  test('no lock means one member and nothing installed', () => {
    const solo = mkdtempSync(join(tmpdir(), 'fli-deps-solo-'))
    writeFileSync(join(solo, 'package.json'), JSON.stringify({ name: 'solo', dependencies: { zod: '^4' } }))
    const r = collectDeps(solo)
    expect(r.members).toHaveLength(1)
    expect(r.uses).toEqual([{ name: 'zod', member: 'solo', kind: 'dependency', range: '^4', installed: null }])
    rmSync(solo, { recursive: true, force: true })
  })
})

describe('depsFindings', () => {
  test('two copies, two non-peer ranges, and a declaration nothing installed', () => {
    const f = depsFindings(collectDeps(ROOT))
    expect(f).toContainEqual({ kind: 'copies', name: 'css-tree', detail: '2.3.1 · 3.2.1' })
    expect(f).toContainEqual({ kind: 'ranges', name: 'css-tree', detail: '^2.3.1 · ^3.0.0' })
    expect(f).toContainEqual({ kind: 'missing', name: 'left-pad', detail: 'app (dependency ^1.3.0)' })
  })

  test('a peer range beside a pin is the design, not a finding', () => {
    expect(depsFindings(collectDeps(ROOT)).filter(f => f.name === 'typescript')).toEqual([])
  })
})

test('the snapshot names its generator and carries no machine path', () => {
  const r  = collectDeps(ROOT)
  const md = renderDepsSnapshot(r)
  expect(md).toContain('<!-- generated by: fli ws:deps -->')
  expect(md).toContain('| `css-tree` | `2.3.1` · `3.2.1` |')
  expect(md).not.toContain(ROOT)
  expect(JSON.stringify(depsPayload(r))).not.toContain(ROOT)
})
