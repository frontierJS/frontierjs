/**
 * `fli mesa:pack` (`FJS-D1934`): a committed page module is only a gate if
 * packing it again gives the same bytes (Invariant 12) and its header is one
 * the `snapshots` phase will rerun. A temp directory name or an absolute path
 * leaking into the bundle passes every render test and fails CI on the next
 * machine, so the pack runs twice from two directories and is compared.
 */
import { describe, test, expect, beforeAll, afterAll } from 'bun:test'
import { mkdtempSync, rmSync, writeFileSync, readFileSync, cpSync } from 'node:fs'
import { tmpdir }                                                    from 'node:os'
import { join, resolve }                                             from 'node:path'
import { spawnSync }                                                 from 'node:child_process'
import { createHash }                                                from 'node:crypto'
import { packMesa }       from '../core/mesa-pack.js'
import { findSnapshots }  from '../core/snapshots.js'

const FLI = resolve(import.meta.dir, '../bin/fli.js')
const CSS = ['@frontierjs/css/foundation/reset', '@frontierjs/css/foundation/tokens', '@frontierjs/css/components/buttons']

const PAGE = `<script>
  export const name = ''
  export const token = ''
</script>

<main class="page">
  <h1>Hello {name}</h1>
  <form method="post"><input type="hidden" name="t" value={token}><button class="btn">Go</button></form>
</main>

<style>
  .page { max-width: 20rem; }
</style>
`

let a, b
beforeAll(() => {
  a = mkdtempSync(join(tmpdir(), 'mesa-pack-a-'))
  b = mkdtempSync(join(tmpdir(), 'mesa-pack-b-'))
  writeFileSync(join(a, 'Page.mesa'), PAGE)
  cpSync(join(a, 'Page.mesa'), join(b, 'Page.mesa'))
})
afterAll(() => { rmSync(a, { recursive: true, force: true }); rmSync(b, { recursive: true, force: true }) })

const fli = (cwd, ...argv) => spawnSync('bun', [FLI, 'mesa:pack', ...argv], { cwd, encoding: 'utf8' })

describe('fli mesa:pack', () => {
  test('two packs from two directories are byte-identical and name neither', async () => {
    const one = await packMesa({ source: join(a, 'Page.mesa'), css: CSS })
    const two = await packMesa({ source: join(b, 'Page.mesa'), css: CSS })
    expect(one).toBe(two)
    expect(one).not.toContain(a)
    expect(one).not.toContain(tmpdir())
    expect(one).not.toContain(resolve(import.meta.dir, '../..'))
  })

  test('the header is one the snapshots phase reruns, and --check is clean then fails on drift', () => {
    const run = fli(a, 'Page.mesa', '--css', CSS.join(','))
    expect(run.status).toBe(0)
    const [snap] = findSnapshots({ root: a })
    expect(snap.error).toBeNull()
    expect(snap.argv).toEqual(['fli', 'mesa:pack', 'Page.mesa', '--css', CSS.join(',')])

    expect(fli(a, ...snap.argv.slice(2), '--check').status).toBe(0)
    writeFileSync(join(a, 'Page.mesa'), PAGE.replace('Hello', 'Goodbye'))
    const drift = fli(a, ...snap.argv.slice(2), '--check')
    writeFileSync(join(a, 'Page.mesa'), PAGE)
    expect(drift.status).toBe(1)
    expect(drift.stdout).toContain('does not match')
  })

  test('--out writes a relative path into the header', () => {
    expect(fli(b, 'Page.mesa', '--out', 'page.snapshot.js').status).toBe(0)
    expect(readFileSync(join(b, 'page.snapshot.js'), 'utf8').split('\n')[0])
      .toBe('/* generated by: fli mesa:pack Page.mesa --out page.snapshot.js */')
  })

  test('render() escapes props, inlines one style and STYLE_HASH is its sha256', async () => {
    const file = join(b, 'Render.snapshot.js')
    writeFileSync(file, await packMesa({ source: join(b, 'Page.mesa'), css: CSS }))
    const { render, STYLE_HASH } = await import(file)
    const html = render({ name: '<script>x</script>', token: 'a"b' })
    expect(html).toStartWith('<!DOCTYPE html>')
    expect(html).toContain('Hello &lt;script&gt;x&lt;/script&gt;')
    expect(html).toContain('value="a&quot;b"')
    expect(html).not.toContain('<script')
    const styles = [...html.matchAll(/<style>([\s\S]*?)<\/style>/g)]
    expect(styles).toHaveLength(1)
    expect(STYLE_HASH).toBe('sha256-' + createHash('sha256').update(styles[0][1]).digest('base64'))
    expect(styles[0][1]).toContain('.btn')
    expect(styles[0][1]).toContain('max-width')
  })

  test('a partial index.css does not import is refused by name', async () => {
    await expect(packMesa({ source: join(a, 'Page.mesa'), css: ['@frontierjs/css/foundation/nope'] }))
      .rejects.toThrow(/foundation\/nope.*no layer/)
  })
})
