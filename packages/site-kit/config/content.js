// config/content.js — what site-kit makes of a site's content/ beyond its routes.
//
// `@content` names the folder, so a block reads `@content/menus/main-menu.md`
// whichever site it renders in. It is an alias with an absolute target, the
// one kind Sierra hands its prerender as well (`pathAliases`), so the name
// resolves in dev, in the bundle and in the render.
//
// The site's settings are content/settings/site.md's front-matter, and each
// key is a name a page uses bare: `{company_name}` in prose. Sierra binds a
// bare name through `autoImport.modules`, which needs a module with one named
// export per key, and a front-matter object is not one. So site-kit writes it,
// `.sierra/settings.js` beside the route table: a real file and not a virtual
// module, because the prerender imports outside Vite, where no plugin answers
// for an id. A block that wants the object reads site.md's `frontmatter`.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { parseFrontmatter } from '@frontierjs/toolbelt/frontmatter'

export const SETTINGS = 'content/settings/site.md'
const MODULE = '.sierra/settings.js'

// `export const <key>` must be an identifier that is not a reserved word, or
// the generated module fails to parse naming a file the author never wrote.
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/
const RESERVED = new Set(('await break case catch class const continue debugger default delete do else enum export extends ' +
  'false finally for function if implements import in instanceof interface let new null package private protected public ' +
  'return static super switch this throw true try typeof var void while with yield').split(' '))

/**
 * content/settings/site.md's front-matter; `{}` for a site without one.
 *
 * @param {string} root — the site directory
 * @returns {Record<string, unknown>}
 */
export function readSettings(root) {
  const file = resolve(root, SETTINGS)
  if (!existsSync(file)) return {}
  const settings = parseFrontmatter(readFileSync(file, 'utf8')).frontmatter ?? {}
  const bad = Object.keys(settings).filter((k) => !IDENTIFIER.test(k) || RESERVED.has(k))
  if (bad.length) throw new Error(`site-kit: ${SETTINGS} names ${bad.map((k) => `'${k}'`).join(', ')}, which a page cannot use bare as {${bad[0]}}; a settings key is a JavaScript name`)
  return settings
}

/**
 * Writes `.sierra/settings.js`, one named export per key.
 *
 * @param {string} root
 * @param {Record<string, unknown>} settings
 * @returns {string} the module's absolute path
 */
export function writeSettingsModule(root, settings) {
  const file = resolve(root, MODULE)
  mkdirSync(dirname(file), { recursive: true })
  const lines = Object.entries(settings).map(([k, v]) => `export const ${k} = ${JSON.stringify(v ?? null)}`)
  writeFileSync(file, `// Generated by site-kit from ${SETTINGS}. Edit that file.\n${lines.join('\n')}\n`)
  return file
}

/**
 * The `@content` alias, and in dev the settings module kept in step with
 * site.md. A changed value rewrites the module and Vite updates what imports
 * it. A key added or removed is said by name: the names Sierra binds bare were
 * fixed when siteKit() made the config, and Vite's own `server.restart()`
 * reuses that config rather than calling siteKit() again.
 *
 * @param {{ root: string, content: string, keys: string[] }} site
 * @returns {import('vite').Plugin}
 */
export function siteContent({ root, content, keys }) {
  const file = resolve(root, SETTINGS)
  return {
    name: 'site-kit:content',
    config: () => ({ resolve: { alias: { '@content': content } } }),
    configureServer(server) {
      server.watcher.add(file)
      server.watcher.on('all', (_, changed) => {
        if (changed !== file) return
        let settings
        try {
          settings = readSettings(root)
        } catch (err) {
          server.config.logger.error(err.message)
          return
        }
        writeSettingsModule(root, settings)
        const now = Object.keys(settings)
        const added = now.filter((k) => !keys.includes(k))
        const removed = keys.filter((k) => !now.includes(k))
        if (added.length || removed.length) {
          server.config.logger.warn(`site-kit: ${SETTINGS} ${[
            added.length && `added ${added.map((k) => `'${k}'`).join(', ')}`,
            removed.length && `removed ${removed.map((k) => `'${k}'`).join(', ')}`,
          ].filter(Boolean).join(' and ')}; stop and start \`site-kit dev\` for a page to name it bare`)
        }
      })
    },
  }
}
