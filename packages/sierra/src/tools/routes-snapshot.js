// tools/routes-snapshot.js — the route table as a committed file
//
// The UI realm's snapshot, beside the Data realm's (`litestone access`,
// `litestone ddl`) and the API realm's (`junction surface`).
//
// A Sierra route table is a NAMING CONVENTION over a file tree: a rename moves a
// URL, a `_module.mesa` appearing one directory up rewraps every page under it,
// and `publishes:` in a page's own frontmatter is the escape from the check that
// otherwise refuses to prerender gated data. Every one of those is a one-line
// diff in a file nobody was reading, and nothing else in the app can see it.
//
// Rendered by `sierra routes`, byte-compared by `sierra routes --check`.
// Never imported by app code.

import { scan } from '../scanner/index.js'

// System-derived flags — restating them beside a path that already shows a
// `:param` is noise, and they cannot be declared, so they cannot drift.
const DERIVED = new Set(['dynamic', 'spread', 'isIndex'])

const WIDTH = 76

// ─── flatten ──────────────────────────────────────────────────────────────────
//
// The scanner nests by URL depth. Sorted flat by path here: a route that gained
// a child would otherwise move its parent's whole subtree in the diff.

function flatten(node, out = []) {
  if (node.file) out.push(node)
  for (const child of node.children ?? []) flatten(child, out)
  return out.sort((a, b) => a.path.localeCompare(b.path))
}

const declaredMeta = (meta = {}) =>
  Object.entries(meta)
    .filter(([k]) => !DERIVED.has(k))
    .sort(([a], [b]) => a.localeCompare(b))

const fmt = (v) => typeof v === 'string' ? v : JSON.stringify(v)

// ─── renderRoutesSnapshot ─────────────────────────────────────────────────────

export function renderRoutesSnapshot(tree, opts = {}) {
  const {
    source  = 'sierra.config.js',
    command = `sierra routes --config ${source}`,
    target  = 'spa',
    routesDir = 'src/routes',
    trailingSlash = 'always',
  } = opts

  const routes  = flatten(tree)
  const layouts = [...new Set(routes.map(r => r.layout).filter(Boolean))].sort()
  const out = []

  out.push('# Route table snapshot')
  out.push('')
  // The machine half: scripts/ci.mjs reads this line and reruns the command
  // with --check from this file's own directory.
  out.push(`<!-- generated by: ${command} -->`)
  out.push('')
  out.push(`Generated from \`${routesDir}\` by \`sierra routes\`. **Do not edit.**`)
  out.push('')
  out.push('A route table is a naming convention over a file tree — a rename moves a URL,')
  out.push('a `_module.mesa` one directory up rewraps every page beneath it, and nothing')
  out.push('in the app refers to either by name. Regenerate after moving a file and read')
  out.push('the diff: a URL that changed without a change you meant to make is a link')
  out.push('somebody else already published.')
  out.push('')
  out.push('```')
  out.push(`${routes.length} route${routes.length === 1 ? '' : 's'} · ${layouts.length} layout${layouts.length === 1 ? '' : 's'} · ` +
           `target ${target} · trailing slash ${trailingSlash}`)
  out.push('```')
  out.push('')

  // ── Publishes ──
  //
  // First, and its own section, for the same reason the access snapshot leads
  // with Unrestricted: this is the line that turns a check off.
  const publishing = routes.filter(r => r.meta?.publishes !== undefined)
  if (target === 'static') {
    out.push('## Publishes')
    out.push('')
    out.push('A prerendered page is public: whatever `load()` read is served to anyone and')
    out.push('cached. The build taps every read and compares it against that model\'s')
    out.push('`@@gate`, fail-closed — `publishes: N` is the declaration that overrides it,')
    out.push('and N is the gate level this page is allowed to publish at. A row appearing')
    out.push('here is a route that was told to publish data a check refused.')
    out.push('')
    if (publishing.length) {
      out.push('| Route | Publishes at | File |')
      out.push('| --- | --- | --- |')
      for (const r of publishing) out.push(`| \`${r.path}\` | ${fmt(r.meta.publishes)} | \`${r.file}\` |`)
    } else {
      out.push('No route declares one — every page is publishing only what the check allows.')
    }
    out.push('')
  } else if (publishing.length) {
    // `publishes` on a route this target never prerenders does nothing at all,
    // which reads exactly like a route that is safe.
    out.push('## Publishes — declared, and inert on this target')
    out.push('')
    out.push('`publishes:` is read by the static build. On a `' + target + '` target nothing')
    out.push('consults it, so a page declaring one is not being checked against anything.')
    out.push('')
    out.push('| Route | Publishes at | File |')
    out.push('| --- | --- | --- |')
    for (const r of publishing) out.push(`| \`${r.path}\` | ${fmt(r.meta.publishes)} | \`${r.file}\` |`)
    out.push('')
  }

  // ── Routes ──
  out.push('## Routes')
  out.push('')
  out.push('`Layout` is the `_module.mesa` the scanner resolved — the nearest one up the')
  out.push('tree, unless the page declared `reset`. Params are the URL\'s own; the meta')
  out.push('column is what the page DECLARED, already merged down the layout chain.')
  out.push('')
  out.push('| Route | File | Layout | Params |')
  out.push('| --- | --- | --- | --- |')
  for (const r of routes) {
    out.push(`| \`${r.path}\` | \`${r.file}\` | ${r.layout ? `\`${r.layout}\`` : '—'} | ` +
             `${r.params?.length ? r.params.map(p => `\`${p}\``).join(', ') : '—'} |`)
  }
  out.push('')

  // ── Meta ──
  const withMeta = routes.map(r => [r, declaredMeta(r.meta)]).filter(([, m]) => m.length)
  out.push('## Declared meta')
  out.push('')
  out.push('Frontmatter, `.meta.js` companion and inherited layout meta, merged the way')
  out.push('the router merges them — layout, then companion, then the page\'s own. A key')
  out.push('arriving from a layout appears on every page under it, which is the change')
  out.push('this section exists to show.')
  out.push('')
  if (withMeta.length) {
    for (const [route, meta] of withMeta) {
      out.push(`- \`${route.path}\` — ${meta.map(([k, v]) => `${k}: \`${fmt(v)}\``).join(' · ')}`)
    }
  } else {
    out.push('No route declares any.')
  }
  out.push('')

  // ── Layouts ──
  out.push('## Layouts')
  out.push('')
  out.push('Every `_module.mesa` reached by a route. One that is here and wraps nothing')
  out.push('you expected is a directory boundary in the wrong place.')
  out.push('')
  for (const layout of layouts) {
    const under = routes.filter(r => r.layout === layout).map(r => r.path)
    out.push(`- \`${layout}\` — ${under.length} route${under.length === 1 ? '' : 's'}: ${under.map(p => `\`${p}\``).join(', ')}`)
  }
  if (!layouts.length) out.push('The app declares none — every page renders on its own.')
  out.push('')

  return out.join('\n').replace(/\n+$/, '\n')
}

// ─── buildRoutesSnapshot ──────────────────────────────────────────────────────
//
// Config in, markdown out. The routes directory is resolved against the CWD
// rather than against the config's location: that is how Sierra itself resolves
// it (Vite's root is `web/`, and `routesDir` is relative to that), and deriving
// it from where the config file sits is the mistake Invariant 3 names.

export async function buildRoutesSnapshot(config, opts = {}) {
  const target        = config.target        ?? 'spa'
  const routesDir     = config.routesDir     ?? 'src/routes'
  const trailingSlash = config.trailingSlash ?? 'always'

  const tree = await scan(routesDir, { trailingSlash, cwd: opts.cwd ?? process.cwd() })

  return renderRoutesSnapshot(tree, { ...opts, target, routesDir, trailingSlash })
}
