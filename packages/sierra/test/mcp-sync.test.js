/**
 * test/mcp-sync.test.js — a `@@sync` model's writes in an MCP App view.
 *
 * A view holds no write: its storage is the host's sandbox origin, and the
 * drain waits on a socket a view never opens, so a held write would sit there
 * unsent. What `@@sync(field)` needs from a LIVE write — the row it was made
 * against — still rides, as the tool call's `_meta`, which the app's
 * `mcp()` reads back into the call's `base` (`IDEAS/agent-client-ui.md`
 * 3.6). The plugin's half is `packages/mcp/test/plugin.test.ts` § the base a
 * view read rides _meta.
 *
 * Its own file because `generateSchemas` resolves its worker path off
 * `import.meta.url`, which `mcp-relay.test.js`'s happy-dom does not give a
 * file scheme.
 */

import { describe, test, expect, beforeEach, afterEach, vi } from 'vitest'
import { mkdtempSync, writeFileSync } from 'fs'
import { tmpdir } from 'os'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

import { mcpApp, _resetMcpApp } from '../src/mcp/index.js'
import { createResource } from '../src/resource/index.js'
import { generateSchemas } from '../src/build/schema-plugin.js'
import { registerSchemas } from '../src/resource/schema-registry.js'
import { pendingQueue, _resetPendingQueue } from '../src/resource/pending.js'

describe('a @@sync model in a view — held nowhere, merged where declared', () => {
  // Generated by the build's own `generateSchemas`, so `x-sync` and the
  // version column are what litestone emits rather than what a test typed.
  const SOURCE = `
model Merge  { id String @id @default(uuid())  name String  v Int @version  @@gate(0.0.0.0)  @@sync(field) }
model Served { id String @id @default(uuid())  name String  v Int @version  @@gate(0.0.0.0)  @@sync(server) }
model Ledger { id String @id @default(uuid())  name String                  @@gate(0.0.0.0)  @@sync(append) }
`
  const ROW = { id: 'M-1', name: 'as read', v: 3 }
  let calls
  const host = {
    async request(method, params) {
      calls.push({ method, params })
      const answer = params.name.endsWith('_find') ? { total: 1, limit: 10, skip: 0, data: [ROW] }
        : params.name.endsWith('_patch') ? { ...ROW, ...params.arguments.data }
        : ROW
      return { content: [{ type: 'text', text: JSON.stringify(answer) }], structuredContent: answer }
    },
  }

  beforeEach(async () => {
    calls = []
    _resetMcpApp()
    _resetPendingQueue()
    const dir  = mkdtempSync(join(tmpdir(), 'sierra-mcp-sync-'))
    const path = join(dir, 'schema.lite')
    writeFileSync(path, SOURCE)
    const g = await generateSchemas(path, () => {}, dirname(dirname(fileURLToPath(import.meta.url))))
    registerSchemas(g.defs, g.models, g.updatePatch)
  })
  afterEach(() => vi.restoreAllMocks())

  test('a field save carries the row it read as _meta, and nothing is queued', async () => {
    mcpApp({ host })
    const merges = createResource('merges', { model: 'Merge' })
    await merges.service.get('M-1')
    await merges.save({ ...ROW, name: 'renamed' })
    expect(calls.at(-1)).toEqual({ method: 'tools/call', params: {
      name: 'merges_patch', arguments: { id: 'M-1', data: { name: 'renamed', v: 3 } }, _meta: { 'frontierjs/base': ROW },
    } })
    expect(pendingQueue().list()).toEqual([])
  })

  test('a policy that only decides a HELD write says nothing: the save leaves as a plain patch', async () => {
    mcpApp({ host })
    for (const [service, model] of [['serveds', 'Served'], ['ledgers', 'Ledger']]) {
      const r = createResource(service, { model })
      await r.service.get('M-1')
      await r.save({ ...ROW, name: 'renamed' })
      expect(calls.at(-1).params).toEqual({ name: `${service}_patch`, arguments: { id: 'M-1', data: model === 'Ledger' ? { name: 'renamed' } : { name: 'renamed', v: 3 } } })
    }
    expect(pendingQueue().list()).toEqual([])
  })

  test('an offlineQuery is not read as a model that declared no @@sync, and asks nothing', async () => {
    mcpApp({ host })
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => {})
    createResource('serveds', { model: 'Served', offlineQuery: { query: {} } })
    await new Promise(r => setTimeout(r, 0))
    expect(calls).toEqual([])
    expect(warn).not.toHaveBeenCalled()
  })
})
