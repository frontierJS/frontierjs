// deploy/caddyfile.mjs — the reverse-proxy config, as a function of the path lists.
//
// Its own module so `build.mjs` (which writes it into the image) and
// `deploy/test/verify-caddy.mjs` (which runs it) share one text: a drive that
// kept its own copy of the matchers would pass while the shipped file did not.

// Caddy has to make the same call the Vite proxy makes: /projects is both a
// service and a page, and only `Accept` tells them apart. A navigation asks for
// text/html and gets the shell; the Junction client asks for JSON and is
// proxied. Matched in that order — the html matcher wins, so a browser typing
// the URL never sees a JSON body.
export function caddyfileFor({ API_PATHS, NAVIGATED_API_PATHS, WS_PATH }, { site = ':80', upstream = 'api:8120' } = {}) {
  const matchers = API_PATHS.map(p => `${p} ${p}/*`).join(' ')
  // A provider sign-in is a navigation to an API redirect, never to a page.
  const navigated = NAVIGATED_API_PATHS.map(p => `${p}*`).join(' ')

  return `# GENERATED by deploy/build.mjs from surface.snapshot.md — do not edit.
{
	admin off
	auto_https off
}

${site} {
	encode gzip

	@ws path ${WS_PATH} ${WS_PATH}/*
	handle @ws {
		reverse_proxy ${upstream}
	}

	# An API path asked for as a document is a NAVIGATION — serve the shell.
	@spa {
		path ${matchers}
		not path ${navigated}
		header Accept *text/html*
	}
	handle @spa {
		rewrite * /index.html
		file_server
	}

	@api path ${matchers}
	handle @api {
		reverse_proxy ${upstream}
	}

	# Everything else: a real file, or the shell. Sierra routes are client-side,
	# so a hard load of /servers/ has to arrive at index.html rather than a 404.
	handle {
		root * /srv
		try_files {path} {path}/index.html /index.html
		file_server
	}
}
`
}
